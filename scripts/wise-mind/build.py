"""Generate schema/wise-mind.cypher from content.py (the single editable source).

Usage (repo root; write to a temp file first so a failed build never empties the file):
  python3 scripts/wise-mind/build.py > /tmp/wm.cypher && mv /tmp/wm.cypher schema/wise-mind.cypher
  python3 scripts/wise-mind/fixture.py
Then run: node --test tests/wise-mind-content.test.mjs
"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from content import *  # noqa: E402,F403

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def q(s): return json.dumps(s, ensure_ascii=False)  # Cypher accepts JSON-style double-quoted strings
def js(o): return q(json.dumps(o, ensure_ascii=False))


def props(d):
    """A Cypher map literal; None values are left out (Neo4j drops a null property anyway)."""
    return "{" + ", ".join(f"{k}: {q(v)}" for k, v in d.items() if v is not None) + "}"


def voice_id(qid, mind, i):
    return f"wm_v_{qid[len('wm_q_'):]}_{mind}_{i + 1}"


def tool_ids():
    src = open(os.path.join(ROOT, "src/data/tools.ts"), encoding="utf8").read()
    return set(re.findall(r"^\s*id: '([a-z0-9-]+)',", src, re.M))


def check():
    qids = [x[0] for x in QUESTIONS]
    pids = [x[0] for x in PRACTICES]
    assert len(set(qids)) == len(qids) and set(VOICES) == set(qids), "every question has its voices"
    for qid, _, practice in QUESTIONS:
        assert practice in pids, (qid, practice)
        for mind in ("emotion", "reason"):
            assert 3 <= len(VOICES[qid][mind]) <= 4, (qid, mind)
    tools = tool_ids()
    for aid, _, nxt, kind in ANSWERS:
        assert all(t in tools for t in nxt), (aid, nxt)
        assert (kind == "quiet") == (not nxt), aid
    for pid, _, _, kind, lines, breaths, seconds in PRACTICES:
        assert kind in ("drift", "hold", "ask"), pid
        assert (breaths is None) == (kind == "drift") and (seconds is None) == (kind != "drift"), pid
    every = json.dumps([QUESTIONS, VOICES, PRACTICES, ANSWERS, FLOW], ensure_ascii=False)
    assert "!" not in every and not re.search(r"\b(should|just|but)\b", every, re.I), "house voice"
check()

L = []
A = L.append
A(f"""// ============================================================
// WISE MIND — {VERSION}
// GENERATED by scripts/wise-mind/build.py from content.py. Edit content.py, not this file.
// The mindfulness tool for when you're torn (docs/design/wise-mind.md): the question, what emotion
// mind and reasonable mind say (MindVoice -VOICES-> WiseMindQuestion), the Handout 3a practices hung
// off dbt_wise_mind (HAS_PRACTICE), what wise mind says (WiseMindAnswer, nextToolIds) and the flow
// copy. Run AFTER invalidation-recovery.cypher (ClinicalSource linehan_skills_2015). Idempotent:
// MERGE + SET += only; constraints live in constraints.cypher.
// ============================================================
""")

A("// --- Flow document (every other line of screens 1-6) ---")
A(f"MERGE (f:WiseMindFlow {{id: 'wise_mind_flow'}})\nSET f += {{version: {q(VERSION)}, contentJson: {js(FLOW)}}};")
A(f"MATCH (f:WiseMindFlow {{id: 'wise_mind_flow'}}), (s:ClinicalSource)\nWHERE s.id IN {q(FLOW['sourceIds'])}\nMERGE (f)-[:GROUNDED_IN]->(s);")
A("MATCH (f:WiseMindFlow {id: 'wise_mind_flow'}), (t:TherapyConcept {id: 'dbt_wise_mind'})\nMERGE (t)-[:IMPLEMENTED_BY_FLOW]->(f);")
A("MATCH (t:TherapyConcept {id: 'dbt_wise_mind'})\nSET t += {whenToUse: \"When you're torn about what to do\", dbtBasis: 'DBT Mindfulness: wise mind (states of mind; ideas for practising wise mind)'};")

A("\n// --- The questions (screen 1) ---")
for i, (qid, label, practice) in enumerate(QUESTIONS):
    A(f"MERGE (n:WiseMindQuestion {{id: {q(qid)}}})\nSET n += {props({'label': label, 'order': i, 'defaultPracticeId': practice, 'version': VERSION})};")

A("\n// --- What each mind says, per question (screen 2) ---")
A("MATCH (:MindVoice)-[r:VOICES]->() DELETE r;")
for qid, _, _ in QUESTIONS:
    for mind in ("emotion", "reason"):
        for i, label in enumerate(VOICES[qid][mind]):
            vid = voice_id(qid, mind, i)
            A(f"MERGE (n:MindVoice {{id: {q(vid)}}})\nSET n += {props({'mind': mind, 'label': label, 'order': i, 'version': VERSION})};")
            A(f"MATCH (v:MindVoice {{id: {q(vid)}}}), (w:WiseMindQuestion {{id: {q(qid)}}})\nMERGE (v)-[:VOICES]->(w);")

A("\n// --- The practices (screen 3), hung off the concept ---")
A("MATCH (:TherapyConcept {id: 'dbt_wise_mind'})-[r:HAS_PRACTICE]->() DELETE r;")
for i, (pid, name, sub, kind, lines, breaths, seconds) in enumerate(PRACTICES):
    A(f"MERGE (n:WiseMindPractice {{id: {q(pid)}}})\nSET n += {props({'name': name, 'sub': sub, 'kind': kind, 'lines': lines, 'breaths': breaths, 'seconds': seconds, 'order': i, 'version': VERSION})};")
    A(f"MATCH (t:TherapyConcept {{id: 'dbt_wise_mind'}}), (p:WiseMindPractice {{id: {q(pid)}}})\nMERGE (t)-[:HAS_PRACTICE]->(p);")

A("\n// --- What wise mind says (screen 4) and where it can go next (screen 6) ---")
for i, (aid, label, nxt, kind) in enumerate(ANSWERS):
    A(f"MERGE (n:WiseMindAnswer {{id: {q(aid)}}})\nSET n += {props({'label': label, 'order': i, 'nextToolIds': nxt, 'kind': kind, 'version': VERSION})};")
CYPHER = "\n".join(L)


if __name__ == "__main__":
    print(CYPHER)
