"""Generate schema/safety-route.cypher from content.py (the single editable source; CORE-01,
docs/design/safety-route.md).

Usage (repo root; write to a temp file first so a failed build never empties the file):
  python3 scripts/safety/build.py > $TMP/s.cypher && mv $TMP/s.cypher schema/safety-route.cypher
  python3 scripts/safety/fixture.py --ship
Then run: node --test tests/safety-route.test.mjs
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from content import *  # noqa: E402,F403


def q(s): return json.dumps(s, ensure_ascii=False)  # Cypher accepts JSON-style double-quoted strings
def js(o): return q(json.dumps(o, ensure_ascii=False, sort_keys=True))


def check():
    ids = [c[0] for c in COUNTRIES]
    assert len(ids) == len(set(ids)), "duplicate country"
    line_ids = [l[0] for l in LINES]
    assert len(line_ids) == len(set(line_ids)), "duplicate line"
    by_id = {l[0]: l for l in LINES}
    for code, _, emergency, _, lines in COUNTRIES:
        assert emergency and emergency.isdigit(), code
        for lid in lines:
            assert lid in by_id and by_id[lid][1] == code, (code, lid)
    for l in LINES:
        lid, country, name, kind, phone, sms, body, chat = l[:8]
        assert kind in LINE_KINDS, lid
        assert phone or sms or chat, f"{lid}: no way to reach it"
        assert any(lid in c[4] for c in COUNTRIES), f"{lid}: no country lists it"
        assert chat is None or chat.startswith("https://"), lid
    assert set(ANSWER_RANK) == {c["id"] for c in FLOW["question"]["choices"]} | {"act"}
    assert set(FLAGS) <= {"crisis_suicidal", "crisis_self_harm", "clinical_referral_shutdown",
                          "clinical_referral_psychosis", "clinical_referral_severe_dissociation"}
    if POLICY["enabled"]:
        assert REVIEW_STATUS != "draft" or APPROVED_TO_SHIP, "the switch is on while the copy is a draft"
    text = json.dumps(FLOW, ensure_ascii=False)
    assert "!" not in text, "no exclamation marks"
    for word in ("promise", "should", " just ", "family", "calm down"):
        assert word not in text.lower(), word


check()

L = []
A = L.append
A(f"""// ============================================================
// SAFETY ROUTE (CORE-01) — {VERSION}
// GENERATED by scripts/safety/build.py from content.py. Edit content.py, not this file.
// SafetyScreenFlow (the question and every screen of the route), Country / CrisisLine (COVERS),
// ASKS_SAFETY (which patterns ask), Emotion.safetyScreen, the SafetyFlag rewrite (userCopy apart
// from the clinician action), core_safety_route / core_means_safety and SafetyPolicy, the switch.
// Off, the check-in behaves exactly as before. Run AFTER knowledge-graph (SafetyFlag, ActivationPattern)
// and emotion-wheel-sync (Emotion). Idempotent: MERGE + SET only. Copy is reviewStatus "{REVIEW_STATUS}".
// ============================================================
""")

A("// --- Clinical sources ---")
for id_, title, url in SOURCES:
    A(f"MERGE (s:ClinicalSource {{id: {q(id_)}}})\nSET s.title = {q(title)}, s.url = {q(url)};")

A("\n// --- Concepts ---")
for cid, name, tool, desc, srcs in CONCEPTS:
    props = f"c.name = {q(name)}, c.description = {q(desc)}, c.module = 'core'"
    if tool:
        props += f", c.appToolId = {q(tool)}"
    A(f"MERGE (c:TherapyConcept {{id: {q(cid)}}})\nSET {props};")
    A(f"MATCH (c:TherapyConcept {{id: {q(cid)}}}), (s:ClinicalSource)\nWHERE s.id IN {q(srcs)}\nMERGE (c)-[:SUPPORTED_BY]->(s);")
A("MATCH (a:TherapyConcept {id: 'core_means_safety'}), (b:TherapyConcept {id: 'core_safety_route'})\nMERGE (a)-[:PART_OF]->(b);")

A("\n// --- The flow ---")
A(f"MERGE (f:SafetyScreenFlow {{id: 'safety_screen'}})\nSET f.version = {q(VERSION)}, f.reviewStatus = {q(REVIEW_STATUS)}, "
  f"f.repeatAfterNoHours = {REPEAT['afterNoHours']}, f.repeatAfterOtherHours = {REPEAT['afterOtherHours']}, f.contentJson = {js(FLOW)};")
A("MATCH (f:SafetyScreenFlow {id: 'safety_screen'}), (c:TherapyConcept {id: 'core_safety_route'})\nMERGE (c)-[:HAS_FLOW]->(f);")

A("\n// --- Which patterns ask (replaces 'TRIGGERS_SAFETY shows the crisis banner' while the policy is on) ---")
A("MATCH (:ActivationPattern)-[r:ASKS_SAFETY]->(:SafetyScreenFlow) DELETE r;")
A(f"MATCH (p:ActivationPattern), (f:SafetyScreenFlow {{id: 'safety_screen'}})\nWHERE p.id IN {q(ASK_PATTERNS)}\nMERGE (p)-[:ASKS_SAFETY]->(f);")

A("\n// --- Emotion.safetyScreen (a word that asks on its own) ---")
A(f"MATCH (e:Emotion) WHERE e.safetyScreen = true AND NOT e.id IN {q(SCREEN_EMOTIONS)}\nSET e.safetyScreen = false;")
A(f"MATCH (e:Emotion) WHERE e.id IN {q(SCREEN_EMOTIONS)}\nSET e.safetyScreen = true;")

A("\n// --- SafetyFlag rewrite (userCopy is the only text a screen may show) ---")
for fid, props in FLAGS.items():
    sets = ", ".join(f"f.{k} = {q(v)}" for k, v in sorted(props.items()))
    A(f"MATCH (f:SafetyFlag {{id: {q(fid)}}})\nSET {sets};")

A("\n// --- Countries and crisis lines (hand-curated; verifiedAt is the audit, never shown) ---")
A("MATCH (:CrisisLine)-[r:COVERS]->(:Country) DELETE r;")
for code, name, emergency, firearm, lines in COUNTRIES:
    A(f"MERGE (c:Country {{id: {q(code)}}})\nSET c.name = {q(name)}, c.emergency = {q(emergency)}, c.firearmPrompt = {'true' if firearm else 'false'}, c.lineIds = {q(lines)};")
for lid, country, name, kind, phone, sms, body, chat, hours, langs, source in LINES:
    order = next(c[4] for c in COUNTRIES if c[0] == country).index(lid)
    A(f"MERGE (l:CrisisLine {{id: {q(lid)}}})\nSET l.name = {q(name)}, l.kind = {q(kind)}, l.phone = {q(phone)}, l.sms = {q(sms)}, "
      f"l.smsBody = {q(body)}, l.chatUrl = {q(chat)}, l.hours = {q(hours)}, l.languages = {q(langs)}, l.source = {q(source)}, "
      f"l.checkedAt = {q(CHECKED)}, l.verifiedAt = null, l.order = {order};")
    A(f"MATCH (l:CrisisLine {{id: {q(lid)}}}), (c:Country {{id: {q(country)}}})\nMERGE (l)-[:COVERS]->(c);")

A("\n// --- The switch ---")
A(f"MERGE (p:SafetyPolicy {{id: {q(POLICY['id'])}}})\nSET p.enabled = {'true' if POLICY['enabled'] else 'false'}, p.version = {q(POLICY['version'])};")
if __name__ == "__main__":
    print("\n".join(L))
