"""Generate schema/please.cypher from content.py (the single editable source).

Usage (repo root; write to a temp file first so a failed build never empties the file):
  python3 scripts/please/build.py > /tmp/please.cypher && mv /tmp/please.cypher schema/please.cypher
Then run: node --test tests/please.test.mjs
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from content import *  # noqa: E402,F403

def q(s): return json.dumps(s, ensure_ascii=False)  # Cypher accepts JSON-style double-quoted strings
def js(o): return q(json.dumps(o, ensure_ascii=False))

def check():
    area_ids = [a["id"] for a in AREAS]
    assert len(set(area_ids)) == len(area_ids) == 5
    ids = [f["id"] for f in FACTORS]
    assert len(set(ids)) == len(ids), "duplicate factor id"
    for f in FACTORS:
        assert f["area"] in area_ids, f["id"]
        assert f["now"] and all(n in NOW for n in f["now"]), f["id"]
        assert f["later"] and all(l in LATER for l in f["later"]), f["id"]
    assert all(n in NOW for n in NOW_ALWAYS) and all(l in LATER for l in LATER_ALWAYS)
    assert all(a in area_ids for a in AREA_FIRST.values())
    assert {c["points"] for c in CHECK} == {"body", "feeling"}
    assert LATER_MAX >= 1
    assert "!" not in json.dumps(COPY) + json.dumps(FACTORS) + json.dumps(NOW) + json.dumps(LATER)
check()

CONTENT = {
    "version": VERSION,
    "areas": AREAS,
    "factors": FACTORS,
    "areaFirst": AREA_FIRST,
    "check": CHECK,
    "now": [{"id": k, "label": v} for k, v in NOW.items()],
    "nowAlways": NOW_ALWAYS,
    "later": [{"id": k, "label": v} for k, v in LATER.items()],
    "laterAlways": LATER_ALWAYS,
    "laterMax": LATER_MAX,
    "copy": COPY,
}

L = []
A = L.append
A(f"""// ============================================================
// PLEASE ("Running low", app tool please-skill) — {VERSION}
// GENERATED by scripts/please/build.py from content.py. Edit content.py, not this file.
// DBT Emotion Regulation, reducing vulnerability: what's running low (PLEASE factors) →
// tired or heavy (check the facts) → one thing right now → protect tomorrow. One flow
// document read by getPleaseContent; nothing about the user is stored.
// Run AFTER invalidation-recovery.cypher (linehan_skills_2015). Idempotent: MERGE + SET only;
// the constraint lives in constraints.cypher. Copy is reviewStatus "{REVIEW_STATUS}".
// ============================================================
""")
A(f"MERGE (f:PleaseFlow {{id: 'please_flow'}})\nSET f.version = {q(VERSION)}, f.reviewStatus = {q(REVIEW_STATUS)}, f.contentJson = {js(CONTENT)};")
A(f"MATCH (f:PleaseFlow {{id: 'please_flow'}}), (c:TherapyConcept {{id: {q(CONCEPT_ID)}}})\nMERGE (f)-[:IMPLEMENTS]->(c);")
A(f"MATCH (f:PleaseFlow {{id: 'please_flow'}}), (s:ClinicalSource)\nWHERE s.id IN {q(SOURCE_IDS)}\nMERGE (f)-[:GROUNDED_IN]->(s);")
A("\n// --- App tool join key (getStateAndTools / getInsightsData cards resolve to the tool) ---")
A(f"MATCH (c:TherapyConcept {{id: {q(CONCEPT_ID)}}})\nSET c.appToolId = {q(APP_TOOL_ID)};")
print("\n".join(L))
