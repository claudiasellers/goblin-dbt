"""Generate schema/cope-ahead.cypher from content.py (the single editable source).

Usage (repo root; write to a temp file first so a failed build never empties the file):
  python3 scripts/cope-ahead/build.py > /tmp/ca.cypher && mv /tmp/ca.cypher schema/cope-ahead.cypher
  python3 scripts/cope-ahead/fixture.py
Then run: node --test tests/cope-ahead-content.test.mjs
"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from content import *  # noqa: E402,F403

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
KINDS = ("body", "words", "action", "tool")


def _dear_man_cope_ahead():
    """DEAR MAN's CopeAhead moves (scripts/dear-man/content.py), for the SAME_MOVE_AS check."""
    import importlib.util
    spec = importlib.util.spec_from_file_location("dear_man_content", os.path.join(ROOT, "scripts/dear-man/content.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.COPE_AHEAD


DEAR_MAN_COPE_AHEAD = _dear_man_cope_ahead()


def q(s): return json.dumps(s, ensure_ascii=False)  # Cypher accepts JSON-style double-quoted strings
def js(o): return q(json.dumps(o, ensure_ascii=False))


def props(d):
    """A Cypher map literal; None values are left out (Neo4j drops a null property anyway)."""
    return "{" + ", ".join(f"{k}: {q(v)}" for k, v in d.items() if v is not None) + "}"


def danger_of(moments):
    """A situation's danger moments, in its order (they are always last)."""
    return [m for m in moments if m in DANGER]


def tool_ids():
    src = open(os.path.join(ROOT, "src/data/tools.ts"), encoding="utf8").read()
    return set(re.findall(r"^\s*id: '([a-z0-9-]+)',", src, re.M))


def check():
    mids = [m[0] for m in HARD_MOMENTS]
    assert len(set(mids)) == len(mids), "hard moment ids are unique"
    assert set(DANGER) <= set(mids), "danger moments exist"
    sids = [s[0] for s in SITUATIONS]
    assert len(set(sids)) == len(sids), "situation ids are unique"
    for sid, _, _, feels, moments in SITUATIONS:
        assert len(feels) == 4, (sid, "four likely feelings")
        assert all(m in mids for m in moments), (sid, moments)
        d = danger_of(moments)
        assert moments[len(moments) - len(d):] == d, (sid, "danger moments are last")
    assert set(PULL_IF) == set(PULLS), "an If for every pull"
    tools = tool_ids()
    ids = [m[0] for m in MOVES]
    assert len(set(ids)) == len(ids), "move ids are unique"
    for mid, kind, label, line, pulls, general, tool, for_moments, for_sits in MOVES:
        assert kind in KINDS, mid
        assert set(pulls) <= set(PULLS), (mid, pulls)
        assert (kind == "tool") == bool(tool), mid
        assert not tool or tool in tools, (mid, tool)
        assert all(m in DANGER for m in for_moments), (mid, "forMoments are danger moments")
        assert not (for_moments and (pulls or general)), (mid, "a danger move shows only for its moment")
        assert set(for_sits) <= set(sids), (mid, for_sits)
        assert not (for_sits and (general or for_moments)), (mid, "a situation-only move is never general or a danger move")
    dm = {x["id"] for x in DEAR_MAN_COPE_AHEAD}
    assert set(SAME_MOVE_AS) | set(SAME_MOVE_HELD) == dm and not set(SAME_MOVE_AS) & set(SAME_MOVE_HELD), "every DEAR MAN move linked or held"
    assert set(SAME_MOVE_AS.values()) <= set(ids), "SAME_MOVE_AS names Cope Ahead moves"
    for d in DANGER:
        assert sum(d in m[7] for m in MOVES) == 1, (d, "exactly one move for each danger moment")
    assert [w[0] for w in WHEN] == ["today", "tomorrow", "this_week", "later"]
    assert all(key in COPY for _, key in WHEN)
    assert len(BEATS) == 7
    every = json.dumps([HARD_MOMENTS, SITUATIONS, PULL_IF, MOVES, BEATS, COPY, AFTER], ensure_ascii=False)
    assert "!" not in every and not re.search(r"\b(should|just|but)\b", every, re.I), "house voice"
check()

L = []
A = L.append
A(f"""// ============================================================
// COPE AHEAD — {VERSION}
// GENERATED by scripts/cope-ahead/build.py from content.py. Edit content.py, not this file.
// Plan for something hard that's coming (docs/design/cope-ahead.md; DBT ER Handout 19): the situations
// (CopeSituation), the hardest moments (HardMoment), what you'll do (CopeMove), the rehearsal
// (RehearsalBeat), all hung off dbt_cope_ahead, and the flow copy, the pull as the "If" and the after
// card (CopeAheadFlow). Run AFTER invalidation-recovery.cypher (ClinicalSource linehan_skills_2015).
// Idempotent: MERGE + SET += only; constraints live in
// constraints.cypher.
// ============================================================
""")

A("// --- Flow document (screen copy, pullIf, the after card) ---")
A(f"MERGE (f:CopeAheadFlow {{id: 'cope_ahead_flow'}})\nSET f.version = {q(VERSION)}, f.contentJson = {js(FLOW)};")
A("\n// --- Sources (if-then plans, imagery) ---")
for sid, title, url in SOURCES:
    A(f"MERGE (s:ClinicalSource {{id: {q(sid)}}})\nSET s += {props({'title': title, 'url': url})};")
A(f"MATCH (f:CopeAheadFlow {{id: 'cope_ahead_flow'}}), (s:ClinicalSource)\nWHERE s.id IN {q(FLOW['sourceIds'])}\nMERGE (f)-[:GROUNDED_IN]->(s);")
A("MATCH (f:CopeAheadFlow {id: 'cope_ahead_flow'}), (t:TherapyConcept {id: 'dbt_cope_ahead'})\nMERGE (t)-[:IMPLEMENTED_BY_FLOW]->(f);")
A("MATCH (t:TherapyConcept {id: 'dbt_cope_ahead'})\nSET t += {whenToUse: \"When something hard is coming and you want to be ready for it\", dbtBasis: 'DBT Emotion Regulation Handout 19: cope ahead'};")

A("\n// --- The hardest moments (screen 3) ---")
A("MATCH (:TherapyConcept {id: 'dbt_cope_ahead'})-[r:HAS_HARD_MOMENT]->() DELETE r;")
for i, (mid, label, if_text) in enumerate(HARD_MOMENTS):
    A(f"MERGE (n:HardMoment {{id: {q(mid)}}})\nSET n += {props({'label': label, 'ifText': if_text, 'order': i, 'version': VERSION})};")
    A(f"MATCH (t:TherapyConcept {{id: 'dbt_cope_ahead'}}), (m:HardMoment {{id: {q(mid)}}})\nMERGE (t)-[:HAS_HARD_MOMENT]->(m);")

A("\n// --- The situations (screens 1-3) ---")
A("MATCH (:TherapyConcept {id: 'dbt_cope_ahead'})-[r:HAS_SITUATION]->() DELETE r;")
for i, (sid, label, after_name, feels, moments) in enumerate(SITUATIONS):
    A(f"MERGE (n:CopeSituation {{id: {q(sid)}}})\nSET n += {props({'label': label, 'afterName': after_name, 'likelyFeelings': feels, 'hardMoments': moments, 'dangerMomentIds': danger_of(moments), 'order': i, 'version': VERSION})};")
    A(f"MATCH (t:TherapyConcept {{id: 'dbt_cope_ahead'}}), (s:CopeSituation {{id: {q(sid)}}})\nMERGE (t)-[:HAS_SITUATION]->(s);")

A("\n// --- What you'll do (screen 4) ---")
A("MATCH (:TherapyConcept {id: 'dbt_cope_ahead'})-[r:HAS_MOVE]->() DELETE r;")
for i, (mid, kind, label, line, pulls, general, tool, for_moments, for_sits) in enumerate(MOVES):
    A(f"MERGE (n:CopeMove {{id: {q(mid)}}})\nSET n += {props({'kind': kind, 'label': label, 'line': line, 'forPulls': pulls, 'general': general, 'appToolId': tool, 'forMoments': for_moments, 'forSituations': for_sits, 'order': i, 'version': VERSION})};")
    A(f"MATCH (t:TherapyConcept {{id: 'dbt_cope_ahead'}}), (m:CopeMove {{id: {q(mid)}}})\nMERGE (t)-[:HAS_MOVE]->(m);")

A("\n// --- DEAR MAN's cope-ahead moves, absorbed (D10): the same move, linked, never renamed or deleted ---")
A("MATCH (:CopeAhead)-[r:SAME_MOVE_AS]->(:CopeMove) DELETE r;")
for ca_id, move_id in SAME_MOVE_AS.items():
    A(f"MATCH (c:CopeAhead {{id: {q(ca_id)}}}), (m:CopeMove {{id: {q(move_id)}}})\nMERGE (c)-[:SAME_MOVE_AS]->(m);")

A("\n// --- The rehearsal (screen 5) ---")
A("MATCH (:TherapyConcept {id: 'dbt_cope_ahead'})-[r:HAS_BEAT]->() DELETE r;")
for i, (bid, text) in enumerate(BEATS):
    A(f"MERGE (n:RehearsalBeat {{id: {q(bid)}}})\nSET n += {props({'text': text, 'order': i + 1, 'version': VERSION})};")
    A(f"MATCH (t:TherapyConcept {{id: 'dbt_cope_ahead'}}), (b:RehearsalBeat {{id: {q(bid)}}})\nMERGE (t)-[:HAS_BEAT]->(b);")
CYPHER = "\n".join(L)


if __name__ == "__main__":
    print(CYPHER)
