"""Generate both copies of the check-in's word list from content.py (the single editable source).

  python3 scripts/emotions/build.py            # rewrite the block in src/data/emotions.ts and schema/emotion-wheel-sync.cypher
  python3 scripts/emotions/build.py --check    # exit 1 if either is stale (tests/emotion-wheel-sync.test.mjs)
  python3 scripts/emotions/build.py --json     # {"square": [ids], "graphOnly": [ids]} for the tests
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from content import SQUARE, GRAPH_ONLY, FAMILY_CORE, OPPOSITE_FAMILIES, CORE  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
TS_PATH = os.path.join(ROOT, "src", "data", "emotions.ts")
CYPHER_PATH = os.path.join(ROOT, "schema", "emotion-wheel-sync.cypher")
TS_START = "// GENERATED by scripts/emotions/build.py from scripts/emotions/content.py: edit content.py, not this list."
TS_END = "// END GENERATED"
QUADRANTS = {"high-unpleasant", "high-pleasant", "low-unpleasant", "low-pleasant"}

words = [w for w in SQUARE if isinstance(w, tuple)]


def check():
    ids = [w[0] for w in words] + [g[0] for g in GRAPH_ONLY]
    dup = {i for i in ids if ids.count(i) > 1}
    assert not dup, f"duplicate ids: {sorted(dup)}"
    for w in words:
        assert len(w) in (6, 7) and (len(w) == 6 or w[6] == CORE), w
        wid, name, quadrant, family, x, y = w[:6]
        assert wid.replace("_", "").isalpha() and wid.islower(), wid
        assert quadrant in QUADRANTS, w
        assert family in FAMILY_CORE, w
        assert 0 <= x <= 1 and 0 <= y <= 1, w
        assert round(x, 2) == x and round(y, 2) == y, f"{wid}: positions have two decimals"
    for g in GRAPH_ONLY:
        assert len(g) == 5 and g[2] in QUADRANTS and g[3] in FAMILY_CORE and g[4].strip(), g
    square_ids = {w[0] for w in words}
    for fam, core in FAMILY_CORE.items():
        assert core in square_ids, f"family {fam}: core {core} is not on the square"
    for a, b in OPPOSITE_FAMILIES:
        assert a in FAMILY_CORE and b in FAMILY_CORE, (a, b)


def ts_block():
    out = [TS_START, "export const emotions: Emotion[] = ["]
    for e in SQUARE:
        if e == "":
            out.append("")
        elif isinstance(e, str):
            out.append(f"  // {e}")
        else:
            wid, name, quadrant, family, x, y = e[:6]
            core = ", true" if len(e) == 7 else ""
            out.append(f"  makeEmotion('{wid}', '{name}', '{quadrant}', '{family}', {x:.2f}, {y:.2f}{core}),")
    out += ["];", TS_END]
    return "\n".join(out)


def ts_file():
    src = open(TS_PATH, encoding="utf8").read()
    if TS_START in src:
        a = src.index(TS_START)
        b = src.index(TS_END, a) + len(TS_END)
    else:  # first run: replace the hand-written list (its comment line + the array)
        a = src.index("// Includes the full user-provided wheel vocabulary")
        b = src.index("\n];", src.index("export const emotions: Emotion[] = [")) + len("\n];")
    return src[:a] + ts_block() + src[b:]


def q(s):
    return json.dumps(s, ensure_ascii=False)


def cypher_file():
    L = ["""// ============================================================
// EMOTION WHEEL SYNC
// GENERATED by scripts/emotions/build.py from scripts/emotions/content.py: edit content.py, not this
// file. Every check-in word on the square (src/data/emotions.ts, generated from the same source) is an
// Emotion node here with the same name, quadrant and family, plus the graph-only words listed in
// content.py (tests/emotion-wheel-sync.test.mjs). Safe to run repeatedly (MERGE + SET; the prunes
// below only remove links between two wheel words that no longer fit their families).
// ============================================================
""", "UNWIND ["]
    rows = []
    for fam in FAMILY_CORE:
        members = [w for w in words if w[3] == fam]
        if members:
            rows.append(f"  // {fam.capitalize()} family")
            rows += [f"  {{id: {q(w[0])}, name: {q(w[1])}, quadrant: {q(w[2])}, family: {q(w[3])}}}," for w in members]
    if GRAPH_ONLY:
        rows.append("  // Graph-only: not on the square (yet); see GRAPH_ONLY in content.py")
        rows += [f"  {{id: {q(g[0])}, name: {q(g[1])}, quadrant: {q(g[2])}, family: {q(g[3])}}}," for g in GRAPH_ONLY]
    last = max(i for i, r in enumerate(rows) if not r.lstrip().startswith("//"))
    rows[last] = rows[last].rstrip(",")
    L += rows
    pairs = ", ".join(f"[{q(a)}, {q(b)}], [{q(b)}, {q(a)}]" for a, b in OPPOSITE_FAMILIES)
    cores = ",\n".join(f"  {{family: {q(f)}, core: {q(c)}}}" for f, c in FAMILY_CORE.items())
    opp = ",\n".join(f"  {{left: {q(a)}, right: {q(b)}}}" for a, b in OPPOSITE_FAMILIES)
    L.append(f"""] AS emotion
MERGE (e:Emotion {{id: emotion.id}})
SET e.name = emotion.name,
    e.quadrant = emotion.quadrant,
    e.family = emotion.family;

// Prune family links that no longer fit a word's family (a word that changes family, like
// "overwhelmed" bad → fearful in Oct 2026, must not keep its old relatives and opposites). Only links
// between two wheel words (both carry `family`); no other schema file links two wheel words
// (tests/emotion-wheel-sync.test.mjs), so nothing else is touched. The MERGEs below rebuild the rest.
MATCH (a:Emotion)-[r:RELATED_TO]->(b:Emotion)
WHERE a.family IS NOT NULL AND b.family IS NOT NULL AND a.family <> b.family
DELETE r;

MATCH (a:Emotion)-[r:OPPOSITE_OF]->(b:Emotion)
WHERE a.family IS NOT NULL AND b.family IS NOT NULL
  AND NOT [a.family, b.family] IN [{pairs}]
DELETE r;

// Related emotions: tie each family to its core emotion.
UNWIND [
{cores}
] AS familyCore
MATCH (core:Emotion {{id: familyCore.core}})
MATCH (member:Emotion {{family: familyCore.family}})
WHERE member.id <> core.id
MERGE (core)-[:RELATED_TO]->(member)
MERGE (member)-[:RELATED_TO]->(core);

// Opposite families.
UNWIND [
{opp}
] AS pair
MATCH (a:Emotion {{family: pair.left}})
MATCH (b:Emotion {{family: pair.right}})
WHERE a.id <> b.id
MERGE (a)-[:OPPOSITE_OF]->(b)
MERGE (b)-[:OPPOSITE_OF]->(a);
""")
    return "\n".join(L)


check()
targets = {TS_PATH: ts_file(), CYPHER_PATH: cypher_file()}

if "--json" in sys.argv:
    print(json.dumps({"square": [w[0] for w in words], "graphOnly": [g[0] for g in GRAPH_ONLY]}))
elif "--check" in sys.argv:
    stale = [os.path.relpath(p, ROOT) for p, text in targets.items() if open(p, encoding="utf8").read() != text]
    if stale:
        print("stale (run python3 scripts/emotions/build.py): " + ", ".join(stale))
        sys.exit(1)
    print("fresh")
else:
    for p, text in targets.items():
        with open(p, "w", encoding="utf8") as fh:
            fh.write(text)
        print("wrote " + os.path.relpath(p, ROOT))
