"""Generate schema/invalidation-recovery.cypher from content.py (the single editable source).

Usage (repo root; write to a temp file first so a failed build never empties the migration):
  python3 scripts/invalidation-recovery/build.py > /tmp/ir.cypher && mv /tmp/ir.cypher schema/invalidation-recovery.cypher
Then run: node --test tests/invalidation-recovery.test.mjs
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from content import *  # noqa: E402,F403
def q(s): return json.dumps(s, ensure_ascii=False)  # Cypher accepts JSON-style double-quoted strings
L = []
A = L.append
A("""// ============================================================
// INVALIDATION RECOVERY ("Recover from a hurtful moment") — recovery-v1
// GENERATED by scripts/invalidation-recovery/build.py from content.py. Edit content.py, not this file.
// Body-first protocol for the invalidated → abandoned cluster.
// Run AFTER opposite-action-flow.cypher. Idempotent: MERGE + SET only,
// constraints IF NOT EXISTS. Links into existing Emotion, ActivationPattern,
// TherapyConcept and ClinicalSource nodes instead of duplicating them.
// App wording is original; see docs/design/recover-from-invalidation.md.
// ============================================================
""")
for c in ["invalidation_event_id:InvalidationEvent","recovery_protocol_id:RecoveryProtocol","unmet_need_id:UnmetNeed","social_need_id:SocialNeed","recovery_exit_id:RecoveryExit","practice_skill_id:PracticeSkill"]:
    n, lab = c.split(":")
    A(f"CREATE CONSTRAINT {n} IF NOT EXISTS\nFOR (n:{lab}) REQUIRE n.id IS UNIQUE;")
A("CREATE CONSTRAINT invalidation_recovery_session_key IF NOT EXISTS\nFOR (s:InvalidationRecoverySession) REQUIRE s.key IS UNIQUE;\n")

A("// --- New therapy concepts (only those not already in knowledge-graph.cypher) ---")
for id_, name, desc, mod, module, parent in NEW_CONCEPTS:
    A(f"MERGE (c:TherapyConcept {{id: {q(id_)}}})\nSET c.name = {q(name)}, c.description = {q(desc)}, c.modality = {q(mod)}" + (f", c.module = {q(module)}" if module else "") + ";")
    if parent:
        rel, target = ("RELATED_TO", parent[4:]) if parent.startswith("rel:") else ("PART_OF", parent)
        A(f"MATCH (c:TherapyConcept {{id: {q(id_)}}}), (m:TherapyConcept {{id: {q(target)}}})\nMERGE (c)-[:{rel}]->(m);")
A("MATCH (t:TherapyConcept {id: 'dbt_recovering_from_invalidation'})\nSET t.whenToUse = 'When someone brushed you off, mocked you, left you out, or pulled away', t.dbtBasis = 'Walking the Middle Path (validation, recovering from invalidation) with STOP, TIPP, Opposite Action and Radical Acceptance; asking hands off to DEAR MAN';")
A("// Recommended by getStateAndTools (normalizeToolId -> 'recovering-from-invalidation') for patterns associated with these emotions.")
A("MATCH (:TherapyConcept {id: 'dbt_recovering_from_invalidation'})-[r:ADDRESSES]->() DELETE r;")
A(f"UNWIND {q(ADDRESSES)} AS eid\nMATCH (t:TherapyConcept {{id: 'dbt_recovering_from_invalidation'}}), (e:Emotion {{id: eid}})\nMERGE (t)-[:ADDRESSES]->(e);\n")

A("// --- Clinical sources ---")
for id_, title, url in SOURCES:
    A(f"MERGE (s:ClinicalSource {{id: {q(id_)}}})\nSET s.title = {q(title)}, s.url = {q(url)};")

A("\n// --- Protocols A–D (validation lines; {N} = name or 'you', {phrase} = state phrase) ---")
A("MATCH (:RecoveryProtocol)-[r:DRAWS_ON]->() DELETE r;")
for pid, (label, lines, concepts) in PROTOCOLS.items():
    A(f"MERGE (p:RecoveryProtocol {{id: {q(pid)}}})\nSET p.label = {q(label)}, p.validationLines = {q(lines)};")
    A(f"UNWIND {q(concepts)} AS cid\nMATCH (p:RecoveryProtocol {{id: {q(pid)}}}), (c:TherapyConcept {{id: cid}})\nMERGE (p)-[:DRAWS_ON]->(c);")

A("\n// --- Invalidation events (what the user taps, in their words) ---")
A("// Clear outgoing edges first so shrinking a list on re-run leaves no stale links.")
A("MATCH (:InvalidationEvent)-[r:HAS_PROTOCOL|OFTEN_FEELS|SIGNALS]->() DELETE r;")
for i, (id_, label, covers, prot, also, phrase, hr, la, emos, pats) in enumerate(STATES):
    A(f"MERGE (w:InvalidationEvent {{id: {q(id_)}}})\nSET w.label = {q(label)}, w.covers = {q(covers)}, w.phrase = {q(phrase)}, w.highRisk = {str(hr).lower()}, w.lowArousal = {str(la).lower()}, w.order = {i};")
    A(f"MATCH (w:InvalidationEvent {{id: {q(id_)}}}), (p:RecoveryProtocol {{id: {q(prot)}}})\nMERGE (w)-[r:HAS_PROTOCOL]->(p) SET r.primary = true;")
    if also:
        A(f"MATCH (w:InvalidationEvent {{id: {q(id_)}}}), (p:RecoveryProtocol {{id: {q(also)}}})\nMERGE (w)-[r:HAS_PROTOCOL]->(p) SET r.primary = false;")
    rows = "[" + ", ".join("{id: %s, rank: %d}" % (q(e), r) for r, e in enumerate(emos)) + "]"
    A(f"UNWIND {rows} AS row\nMATCH (w:InvalidationEvent {{id: {q(id_)}}}), (e:Emotion {{id: row.id}})\nMERGE (w)-[r:OFTEN_FEELS]->(e) SET r.rank = row.rank;")
    A(f"UNWIND {q(pats)} AS pid\nMATCH (w:InvalidationEvent {{id: {q(id_)}}}), (a:ActivationPattern {{id: pid}})\nMERGE (w)-[:SIGNALS]->(a);")

A("\n// --- Social needs (Williams) and unmet needs ---")
A("MATCH (:SocialNeed)-[r:RESTORED_BY]->() DELETE r;")
A("MATCH (:UnmetNeed)-[r:THREATENS]->() DELETE r;")
for id_, (title, act, concept, skill) in SOCIAL.items():
    A(f"MERGE (s:SocialNeed {{id: {q(id_)}}})\nSET s.elsewhereTitle = {q(title)}, s.elsewhereAct = {q(act)}, s.practiceSkill = {q(skill)};")
    A(f"MATCH (s:SocialNeed {{id: {q(id_)}}}), (c:TherapyConcept {{id: {q(concept)}}})\nMERGE (s)-[:RESTORED_BY]->(c);")
for i, (id_, label, social) in enumerate(NEEDS):
    A(f"MERGE (n:UnmetNeed {{id: {q(id_)}}})\nSET n.label = {q(label)}, n.order = {i};")
    A(f"MATCH (n:UnmetNeed {{id: {q(id_)}}}), (s:SocialNeed {{id: {q(social)}}})\nMERGE (n)-[:THREATENS]->(s);")

A("\n// --- Exits ---")
A("MATCH (:RecoveryExit)-[r:IMPLEMENTS]->() DELETE r;")
for i, (id_, title, sub, chaseSub, concepts) in enumerate(EXITS):
    A(f"MERGE (x:RecoveryExit {{id: {q(id_)}}})\nSET x.title = {q(title)}, x.sub = {q(sub)}, x.chaseSub = {q(chaseSub) if chaseSub else 'null'}, x.order = {i};")
    A(f"UNWIND {q(concepts)} AS cid\nMATCH (x:RecoveryExit {{id: {q(id_)}}}), (c:TherapyConcept {{id: cid}})\nMERGE (x)-[:IMPLEMENTS]->(c);")

A("\n// --- Practice skill deck (grades follow the project's Strong/Moderate/Preliminary scale;")
A("// evidenceBasis says why a skill is Preliminary) ---")
# Scoped to Recover's own skills: other modules add PracticeSkills too (plan F5, PR-S2).
A(f"MATCH (k:PracticeSkill)-[r:PRACTICES|SUPPORTED_BY]->() WHERE k.id IN {q([s[0] for s in SKILLS])} DELETE r;")
for i, (id_, name, grade, fam, concept, why) in enumerate(SKILLS):
    basis = "Clinical consensus" if grade == "Clinical consensus" else ("Limited trials" if grade == "Preliminary" else None)
    g = "Preliminary" if grade == "Clinical consensus" else grade
    A(f"MERGE (k:PracticeSkill {{id: {q(id_)}}})\nSET k.name = {q(name)}, k.evidenceGrade = {q(g)}, k.evidenceBasis = {q(basis) if basis else 'null'}, k.family = {q(fam)}, k.why = {q(why)}, k.order = {i};")
    A(f"MATCH (k:PracticeSkill {{id: {q(id_)}}}), (c:TherapyConcept {{id: {q(concept)}}})\nMERGE (k)-[:PRACTICES]->(c);")
    if SKILL_SOURCES.get(id_):
        A(f"UNWIND {q(SKILL_SOURCES[id_])} AS sid\nMATCH (k:PracticeSkill {{id: {q(id_)}}}), (s:ClinicalSource {{id: sid}})\nMERGE (k)-[:SUPPORTED_BY]->(s);")

A("\n// --- Flow document (copy + gate thresholds), versioned like OppositeActionFlow ---")
A(f"MERGE (f:InvalidationRecoveryFlow {{id: 'invalidation_recovery_flow'}})\nSET f.version = {q(FLOW['version'])}, f.contentJson = {q(json.dumps(FLOW, ensure_ascii=False))};")
A(f"MATCH (f:InvalidationRecoveryFlow {{id: 'invalidation_recovery_flow'}}), (s:ClinicalSource)\nWHERE s.id IN {q(FLOW['sourceIds'])}\nMERGE (f)-[:GROUNDED_IN]->(s);")
A("MATCH (f:InvalidationRecoveryFlow {id: 'invalidation_recovery_flow'}), (p:RecoveryProtocol)\nMERGE (f)-[:INCLUDES_PROTOCOL]->(p);")
A("MATCH (f:InvalidationRecoveryFlow {id: 'invalidation_recovery_flow'}), (t:TherapyConcept {id: 'dbt_recovering_from_invalidation'})\nMERGE (t)-[:IMPLEMENTED_BY_FLOW]->(f);")
A("\nCREATE INDEX invalidation_recovery_session_created IF NOT EXISTS\nFOR (s:InvalidationRecoverySession) ON (s.createdAt);")
print("\n".join(L))
