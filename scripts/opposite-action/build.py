"""Regenerate schema/opposite-action-data.cypher from scripts/opposite-action/content.py (the one editable source).

  python3 scripts/opposite-action/build.py              # write the file
  python3 scripts/opposite-action/build.py --check      # exit 1 if the file is stale
  python3 scripts/opposite-action/build.py --prove REF  # same statements as the file at a git ref (whitespace aside)
"""
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import content as C  # noqa: E402

OUT = os.path.join(ROOT, "schema/opposite-action-data.cypher")
PARENTS = ["fear", "anger", "sadness", "disgust", "shame", "guilt", "jealousy", "envy", "love"]


def lit(v):
    if v is None:
        return "null"
    if v is True:
        return "true"
    if v is False:
        return "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, list):
        return "[" + ", ".join(lit(x) for x in v) + "]"
    return json.dumps(v, ensure_ascii=False)


def row(r):
    return "{" + ", ".join(f"{k}: {lit(v)}" for k, v in r.items()) + "}"


def unwind(rows, var):
    return "UNWIND [\n" + ",\n".join(f"  {row(r)}" for r in rows) + f"\n] AS {var}"


def rule(*lines):
    return "// " + "=" * 60 + "\n" + "\n".join(f"// {x}" for x in lines) + "\n// " + "=" * 60


HEADER = """// ============================================================
// OPPOSITE ACTION DATA — Protocol metadata, Action Urges,
// and per-emotion OA mapping properties.
//
// GENERATED by scripts/opposite-action/build.py from scripts/opposite-action/content.py: edit content.py, never
// this file.
//
// Run AFTER emotion-regulation-content.cypher (which creates
// EmotionRegulationContent nodes and base properties).
//
// This adds:
//   1. Protocol metadata (fitsFactsGuidance, whyItWorks, etc.)
//   2. ActionUrge nodes with graduated opposites
//   3. Per-emotion OA applicability + clinical notes
//   4. HAS_REGULATION_CONTENT relationships for all applicable emotions
//
// All operations use MERGE — safe to re-run.
// ============================================================


// --- CONSTRAINT ---
CREATE CONSTRAINT action_urge_id IF NOT EXISTS
FOR (u:ActionUrge) REQUIRE u.id IS UNIQUE;
"""


def generated():
    assert [p for p, _ in C.PROTOCOL] == PARENTS and [p for p, _ in C.PARENT_URGES] == PARENTS, "one block per parent, in order"
    ids = [u["id"] for _, us in C.PARENT_URGES for u in us] + [u["id"] for u in C.INTERPERSONAL] + [u["id"] for u in C.BEHAVIOUR]
    assert len(ids) == len(set(ids)), "an ActionUrge id is used once"
    for u in C.INTERPERSONAL:
        assert u["parents"] and all(p in PARENTS for p in u["parents"]), u["id"]
    for b in C.EMOTION_BLOCKS:
        if b[0] == "rows":
            for r in b[2]:
                # A parent means Do the Opposite applies: the link below is made for every row that names one.
                assert (r["parent"] is not None) == r["applicable"] and (r["parent"] is None or r["parent"] in PARENTS), r["id"]
    out = [HEADER, "", rule("1. PROTOCOL METADATA on EmotionRegulationContent nodes",
                             "   Adds: fitsFactsGuidance, whyItWorks, acknowledgment,",
                             "   bodyOpposite, defaultOppositeSmall/Medium/Bigger"), ""]
    for p, props in C.PROTOCOL:
        sets = ",\n    ".join(f"c.{k} = {lit(v)}" for k, v in props.items())
        out += [f"// --- {p.upper()} ---", f"MATCH (c:EmotionRegulationContent {{dbtParent: '{p}'}})", f"SET {sets};", ""]
    out += ["", rule("2. ACTION URGE NODES", "   Graduated opposite actions (small / medium / bigger)",
                     "   per specific action urge within each parent."), ""]
    for p, urges in C.PARENT_URGES:
        out += [f"// --- {p.upper()} urges ---", f"MATCH (c:EmotionRegulationContent {{dbtParent: '{p}'}})", "WITH c",
                unwind(urges, "urge"), "MERGE (u:ActionUrge {id: urge.id})",
                "SET u.label = urge.label, u.small = urge.small, u.medium = urge.medium, u.bigger = urge.bigger, u.order = urge.order",
                "MERGE (c)-[:HAS_ACTION_URGE]->(u);", ""]
    out += ["", "// --- INTERPERSONAL urges (ER-03 item 8: the urges Recover's design record asks for) ---",
            "// What a hurt pulls toward with one person. One node per urge, listed under every parent it belongs to; after each",
            "// parent's own urges (`order`). Each is mapped for parts in scripts/parts/content.py.",
            unwind(C.INTERPERSONAL, "urge"), "MERGE (u:ActionUrge {id: urge.id})",
            "SET u.label = urge.label, u.small = urge.small, u.medium = urge.medium, u.bigger = urge.bigger, u.order = urge.order, u.interpersonal = true",
            "WITH u, urge", "UNWIND urge.parents AS parent", "MATCH (c:EmotionRegulationContent {dbtParent: parent})",
            "MERGE (c)-[:HAS_ACTION_URGE]->(u);", "",
            rule("3. PER-EMOTION OA PROPERTIES + HAS_REGULATION_CONTENT", "   Sets oppositeActionApplicable, oaClinicalNote,",
                 "   oaAlternativeSkill on every Emotion node, and creates", "   HAS_REGULATION_CONTENT for applicable emotions."), ""]
    for b in C.EMOTION_BLOCKS:
        if b[0] == "rows":
            _, title, rows = b
            out += [f"// --- {title} ---", unwind(rows, "m"), "MATCH (e:Emotion {id: m.id})",
                    "SET e.oppositeActionApplicable = m.applicable, e.oaClinicalNote = m.note, e.oaAlternativeSkill = m.alt",
                    "WITH e, m", "WHERE m.parent IS NOT NULL", "MATCH (c:EmotionRegulationContent {dbtParent: m.parent})",
                    "MERGE (e)-[:HAS_REGULATION_CONTENT]->(c);", ""]
        elif b[0] == "ids":
            _, title, ids_, note, alt = b
            out += [f"// --- {title} ---", f"UNWIND {lit(ids_)} AS id", "MATCH (e:Emotion {id: id})",
                    "SET e.oppositeActionApplicable = false,", f"    e.oaClinicalNote = {lit(note)},",
                    f"    e.oaAlternativeSkill = {lit(alt)};", ""]
        else:
            _, eid, note, alt = b
            out += [f"MATCH (e:Emotion {{id: {lit(eid)}}})", "SET e.oppositeActionApplicable = false,",
                    f"    e.oaClinicalNote = {lit(note)},", f"    e.oaAlternativeSkill = {lit(alt)};", ""]
    out += ["// --- BEHAVIOUR URGES (DT-02 Hold to wait; plan C5: DT adds behaviour urges, self_harm as a reviewed row) ---",
            "// What the person is about to do, not what a feeling pulls toward, so no HAS_ACTION_URGE: Do the Opposite's urge",
            "// lists never show them. Hold to wait's *What's pulling at you?* chips record these ids as the session's urgeIds;",
            "// DT-05 Ride it out and DT-10 Pros & cons use the same vocabulary. `use` covers use, drink, binge and buy until",
            "// DT-09's substance scope is decided (D14). self_harm is life-threatening: every flow that names it opens",
            "// safety.open first (plan C6.5). Mapped (or held) for parts in scripts/parts/content.py.",
            unwind(C.BEHAVIOUR, "urge"), "MERGE (u:ActionUrge {id: urge.id})",
            'SET u.label = urge.label, u.kind = "behaviour", u.lifeThreatening = urge.lifeThreatening, u.module = "dt";']
    return "\n".join(out) + "\n"


def statements(text):
    """Statements with comments dropped and whitespace collapsed: what the database sees."""
    text = "\n".join(l for l in text.split("\n") if not l.strip().startswith("//"))
    return [re.sub(r"\s+", " ", s).replace("[ ", "[").replace(" ]", "]").strip() for s in text.split(";") if s.strip()]


def main(argv):
    text = generated()
    if "--check" in argv:
        if open(OUT, encoding="utf8").read() != text:
            print("schema/opposite-action-data.cypher is stale: run python3 scripts/opposite-action/build.py", file=sys.stderr)
            return 1
        return 0
    if "--prove" in argv:
        ref = argv[argv.index("--prove") + 1]
        old = subprocess.run(["git", "show", f"{ref}:schema/opposite-action-data.cypher"], cwd=ROOT, check=True,
                             capture_output=True, text=True).stdout
        a, b = statements(old), statements(text)
        if a != b:
            for i, (x, y) in enumerate(zip(a, b)):
                if x != y:
                    print(f"statement {i} differs:\n  {x[:400]}\n  {y[:400]}", file=sys.stderr)
                    break
            print(f"{len(a)} vs {len(b)} statements", file=sys.stderr)
            return 1
        print(f"same {len(a)} statements as {ref}")
        return 0
    open(OUT, "w", encoding="utf8").write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
