"""Generate schema/witness.cypher from content.py (the single editable source).

Usage (repo root; write to a temp file first so a failed build never empties the file):
  python3 scripts/witness/build.py > /tmp/w.cypher && mv /tmp/w.cypher schema/witness.cypher
Then: node --test tests/voice-lint.test.mjs tests/witness-content.test.mjs

Each batch of lines is also written as one line of JSON after a `// @corpus-json ` marker, so the
voice lint (scripts/voice-lint.mjs, npm test, the loader) reads the corpus without Python.
"""
import json, os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
from content import (VERSION, MOMENTS, SOURCE_IDS, LINES, LEVELS, KINDS, BANDS, STATUSES, FAMILIES)  # noqa: E402

RULES = json.load(open(os.path.join(here, "voice-rules.json")))


def q(s): return json.dumps(s, ensure_ascii=False)  # Cypher accepts JSON-style double-quoted strings


def cmap(d):
    return "{" + ", ".join(f"{k}: {q(v)}" for k, v in d.items()) + "}"


def check():
    ids = [l["id"] for l in LINES]
    assert len(ids) == len(set(ids)), "duplicate line id"
    moment_ids = {m[0] for m in MOMENTS}
    for l in LINES:
        assert re.fullmatch(r"[a-z][a-z0-9_]{2,63}", l["id"]), l["id"]
        assert l["level"] in LEVELS and l["kind"] in KINDS and l["status"] in STATUSES, l["id"]
        assert l["reviewStatus"] in ("reviewed", "draft"), l["id"]
        assert all(b in BANDS for b in l["bands"]) and l["bands"], l["id"]
        assert all(m in moment_ids for m in l["moments"]), l["id"]
        assert all(f in FAMILIES for f in l["families"]), l["id"]
check()

# What the graph stores per line (targets become edges; `note` stays in the source).
ROW_KEYS = ["id", "text", "textNamed", "level", "voice", "bands", "kind", "forOther", "tentative", "order",
            "status", "reviewStatus", "reviewedAt"]
rows = []
for i, l in enumerate(LINES):
    r = {k: l.get(k) for k in ROW_KEYS if k != "order"}
    r["order"] = i
    rows.append(r)

# The lint also needs the level-3 guesses (UNDERNEATH); they ride in the corpus JSON only.
lint_rows = [dict(r, underneath=l["underneath"]) for r, l in zip(rows, LINES)]

L = []
A = L.append
A(f"""// ============================================================
// WITNESS CORPUS (WMP-01) — {VERSION} (plan A5-1)
// GENERATED by scripts/witness/build.py from content.py. Edit content.py, not this file.
// ValidationLine: the validation layer's lines, level 1-6, tagged by band, kind and target
// (word, DBT family, situation, urge, tool moment). getWitnessLines serves only status "live";
// "draft" lines are loaded for review and never served. VoiceRule mirrors the voice contract
// (scripts/witness/voice-rules.json), which the loader lints this file against before sending it.
// Run AFTER invalidation-recovery.cypher (RecoveryProtocol, ClinicalSource), emotion-regulation-
// content.cypher (EmotionRegulationContent), opposite-action-data.cypher (ActionUrge) and
// dear-man-debrief-content.cypher (TurningPoint). Idempotent: MERGE + SET; constraints live in
// constraints.cypher. Lines dropped from the source are retired, never deleted.
// ============================================================
""")

A("// --- Tool moments ---")
A("UNWIND " + "[" + ", ".join(cmap({"id": i, "hostToolId": h, "label": lab}) for i, h, lab in MOMENTS) + "]"
  + " AS row\nMERGE (m:ToolMoment {id: row.id})\nSET m.hostToolId = row.hostToolId, m.label = row.label;")

A("\n// --- Voice rules (traceability; the lint reads scripts/witness/voice-rules.json) ---")
vr = [{"id": r["id"], "pattern": r.get("pattern"), "flags": r.get("flags"), "severityJson": json.dumps(r["severity"]),
       "message": r["message"], "ruleVersion": RULES["version"]} for r in RULES["rules"] + RULES["structural"]]
A("UNWIND [" + ", ".join(cmap(v) for v in vr) + "] AS row\nMERGE (v:VoiceRule {id: row.id})\n"
  "SET v.pattern = row.pattern, v.flags = row.flags, v.severityJson = row.severityJson, v.message = row.message, v.ruleVersion = row.ruleVersion;")

A("\n// --- Lines (batches; each preceded by its corpus JSON for the lint) ---")
BATCH = 30
for b in range(0, len(rows), BATCH):
    chunk = rows[b:b + BATCH]
    A("// @corpus-json " + json.dumps(lint_rows[b:b + BATCH], ensure_ascii=False))
    A("UNWIND [" + ", ".join(cmap(r) for r in chunk) + "] AS row\n"
      "MERGE (l:ValidationLine {id: row.id})\n"
      "SET l.text = row.text, l.textNamed = row.textNamed, l.level = row.level, l.voice = row.voice, l.bands = row.bands,\n"
      "    l.kind = row.kind, l.forOther = row.forOther, l.tentative = row.tentative, l.order = row.order,\n"
      f"    l.status = row.status, l.reviewStatus = row.reviewStatus, l.reviewedAt = row.reviewedAt, l.corpusVersion = {q(VERSION)};")

A("\n// Lines no longer in the source are retired (kept: SHOWED_LINE history points at them).")
A(f"MATCH (l:ValidationLine) WHERE NOT l.id IN {q([r['id'] for r in rows])}\nSET l.status = 'retired';")

A("\n// --- Content edges: cleared and rebuilt, so a shrinking list leaves no stale edge ---")
A("MATCH (:ValidationLine)-[r:VALIDATES|VALIDATES_FAMILY|UNDERNEATH|FOR_SITUATION|FOR_URGE|FOR_MOMENT|GROUNDED_IN]->() DELETE r;")


def edges(title, pairs, match, rel):
    if not pairs:
        return
    A(f"// {title}")
    A("UNWIND [" + ", ".join(cmap({"line": a, "to": b}) for a, b in pairs) + "] AS row\n"
      f"MATCH (l:ValidationLine {{id: row.line}}), {match}\nMERGE (l)-[:{rel}]->(t);")


edges("moments", [(l["id"], m) for l in LINES for m in l["moments"]], "(t:ToolMoment {id: row.to})", "FOR_MOMENT")
for label in sorted({s[0] for l in LINES for s in l["situations"]}):
    edges(f"situations: {label}", [(l["id"], s[1]) for l in LINES for s in l["situations"] if s[0] == label],
          f"(t:{label} {{id: row.to}})", "FOR_SITUATION")
edges("specific words", [(l["id"], w) for l in LINES for w in l["words"]], "(t:Emotion {id: row.to})", "VALIDATES")
edges("DBT families (4 of the 9 parents aren't Emotion ids, so families go to EmotionRegulationContent)",
      [(l["id"], f) for l in LINES for f in l["families"]], "(t:EmotionRegulationContent {dbtParent: row.to})", "VALIDATES_FAMILY")
edges("level-3 guesses", [(l["id"], u) for l in LINES for u in l["underneath"]], "(t:Emotion {id: row.to})", "UNDERNEATH")
edges("urges", [(l["id"], u) for l in LINES for u in l["urges"]], "(t:ActionUrge {id: row.to})", "FOR_URGE")
A("// sources")
A(f"MATCH (l:ValidationLine), (t:ClinicalSource) WHERE l.corpusVersion = {q(VERSION)} AND t.id IN {q(SOURCE_IDS)}\n"
  "MERGE (l)-[:GROUNDED_IN]->(t);")

print("\n".join(L))
