def build_content():
    L = [f"""{RULE}
// DEAR MAN CONTENT — Situation types, guided options,
// barrier coaching, negotiate options, debrief options.
{GENERATED}
//
// All operations use MERGE — safe to re-run.
// Chunked per Aura requirement (no variable persistence).
{RULE}


// --- CONSTRAINTS ---
"""]
    for name, var, label in [
        ("dearman_situation_type_id", "s", "DearManSituationType"), ("dearman_describe_option_id", "d", "DearManDescribeOption"),
        ("dearman_assert_option_id", "a", "DearManAssertOption"), ("dearman_reinforce_option_id", "r", "DearManReinforceOption"),
        ("dearman_barrier_id", "b", "DearManBarrier"), ("dearman_barrier_coaching_id", "c", "DearManBarrierCoaching"),
        ("dearman_anchor_phrase_id", "a", "DearManAnchorPhrase"), ("dearman_negotiate_option_id", "n", "DearManNegotiateOption"),
        ("dearman_debrief_option_id", "d", "DearManDebriefOption"), ("dearman_step_insight_id", "i", "DearManStepInsight"),
        ("dearman_feeling_chip_id", "f", "DearManFeelingChip"), ("dearman_session_id", "s", "DearManSession"),
    ]:
        L.append(constraint(name, var, label) + "\n\n")
    L[-1] = L[-1].rstrip("\n")

    L.append(section("1. SITUATION TYPES"))
    L.append("\n\n".join(merge("s", "DearManSituationType", r["id"], {k: v for k, v in r.items() if k != "id"}) + ";" for r in C.SITUATION_TYPES))

    L.append(section("2. DESCRIBE OPTIONS (per situation type)"))
    blocks = []
    for st, rows in C.DESCRIBE_OPTIONS.items():
        blocks.append(f"// --- {st.upper()} ---\n" + unwind(rows, "d") + f"""
MERGE (opt:DearManDescribeOption {{id: d.id}})
SET opt.label = d.label, opt.sortOrder = d.sort
WITH opt, d
MATCH (s:DearManSituationType {{id: '{st}'}})
MERGE (opt)-[:FOR_SITUATION]->(s);""")
    L.append("\n\n".join(blocks))

    L.append(section("3. ASSERT OPTIONS (per situation type)"))
    # The hand-written blocks set hasPlaceholder three ways; kept, so the load is unchanged.
    placeholder = {"ask": "a.hasPlaceholder", "boundary": "a.hasPlaceholder", "address": "false", "pattern": "coalesce(a.hasPlaceholder, false)"}
    blocks = []
    for st, rows in C.ASSERT_OPTIONS.items():
        blocks.append(f"// --- {st.upper()} ---\n" + unwind(rows, "a") + f"""
MERGE (opt:DearManAssertOption {{id: a.id}})
SET opt.label = a.label, opt.hasPlaceholder = {placeholder[st]}, opt.sortOrder = a.sort
WITH opt, a
MATCH (s:DearManSituationType {{id: '{st}'}})
MERGE (opt)-[:FOR_SITUATION]->(s);""")
    L.append("\n\n".join(blocks))

    L.append(section("4. REINFORCE OPTIONS (universal — not per situation type)"))
    L.append(unwind(C.REINFORCE_OPTIONS, "r") + "\nMERGE (opt:DearManReinforceOption {id: r.id})\nSET opt.label = r.label, opt.sortOrder = r.sort;")

    L.append(section("5. BARRIERS + BARRIER COACHING"))
    L.append(unwind(C.BARRIERS, "b") + "\nMERGE (bar:DearManBarrier {id: b.id})\nSET bar.label = b.label;\n\n// --- Coaching per barrier ---\n")
    coach = []
    for r in C.BARRIER_COACHING:
        props = {k: v for k, v in r.items() if k not in ("id", "barrier")}
        s = merge("c", "DearManBarrierCoaching", r["id"], props)
        if r.get("barrier"):
            s += f"\nWITH c\nMATCH (b:DearManBarrier {{id: {lit(r['barrier'])}}})\nMERGE (c)-[:ADDRESSES]->(b)"
        else:
            s = "// --- Default coaching (no specific barrier) ---\n" + s
        coach.append(s + ";")
    L.append("\n\n".join(coach))

    L.append(section("6. ANCHOR PHRASES"))
    L.append(unwind(C.ANCHOR_PHRASES_V1, "a") + "\nMERGE (p:DearManAnchorPhrase {id: a.id})\nSET p.label = a.label, p.sortOrder = a.sortOrder;")

    L.append(section("7. NEGOTIATE OPTIONS"))
    neg = "\nMERGE (opt:DearManNegotiateOption {id: n.id})\nSET opt.label = n.label, opt.type = n.type, opt.sortOrder = n.sort;"
    L.append("// --- Middle ground ---\n" + unwind(C.NEGOTIATE_MIDDLE_GROUND, "n") + neg + "\n\n// --- Walk-away ---\n" + unwind(C.NEGOTIATE_WALK_AWAY, "n") + neg)
    L.append("\n\n// --- Priority-aware negotiate hints ---\n// Stored as properties on the DEAR MAN TherapyConcept node\n" + concept(C.NEGOTIATE_HINTS))

    L.append(section("8. FEELING CHIPS (curated interpersonal feeling words)"))
    L.append(unwind(C.FEELING_CHIPS, "f") + "\nMERGE (chip:DearManFeelingChip {id: f.id})\nSET chip.label = f.label, chip.sortOrder = f.sort;")

    L.append(section("9. STEP INSIGHTS (one-liner per DEAR step)"))
    L.append(unwind(C.STEP_INSIGHTS, "i") + "\nMERGE (ins:DearManStepInsight {id: i.id})\nSET ins.step = i.step, ins.text = i.text;")

    L.append(section("10. DEBRIEF OPTIONS"))
    deb = "\nMERGE (opt:DearManDebriefOption {id: d.id})\nSET opt.label = d.label, opt.type = d.type, opt.sortOrder = d.sort;"
    L.append("// --- What went well ---\n" + unwind(C.DEBRIEF_WENT_WELL, "d") + deb + "\n\n// --- What to try differently ---\n" + unwind(C.DEBRIEF_TO_CHANGE, "d") + deb)

    L.append(section("11. REVEAL TEXT (stored on TherapyConcept node)"))
    L.append(concept(C.CONCEPT_COPY))

    L.append(section("12. CONFIDENCE CUES (Appear confident: body and voice, IE-B2)"))
    L.append(unwind(C.CONFIDENCE_CUES, "c") + "\nMERGE (cue:ConfidenceCue {id: c.id})\nSET cue.label = c.label, cue.kind = c.kind, cue.sortOrder = c.sortOrder\nWITH cue\n" + DEAR + "\nMERGE (cue)-[:IMPLEMENTS]->(tc);")
    return "".join(L) + "\n"


