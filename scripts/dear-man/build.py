GENERATED = "// GENERATED by scripts/dear-man/build.py from scripts/dear-man/content.py. Edit content.py, not this file."
RULE = "// ============================================================"


def lit(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, str):
        # Single quotes, as the hand-written files mostly had; double when the text has an apostrophe.
        if "'" not in v and "\\" not in v:
            return "'" + v + "'"
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        return "[" + ", ".join(lit(x) for x in v) + "]"
    raise TypeError(v)


def unwind(rows, var):
    """UNWIND [ {k: v, …}, … ] AS var, one row per line, columns aligned."""
    segs = [[f"{k}: {lit(v)}" for k, v in r.items()] for r in rows]
    width = {}
    for s in segs:
        for j, x in enumerate(s[:-1]):
            width[j] = max(width.get(j, 0), len(x) + 1)
    lines = []
    for n, s in enumerate(segs):
        cells = [(x + ",").ljust(width[j] + 1) if j < len(s) - 1 else x for j, x in enumerate(s)]
        lines.append("  {" + "".join(cells) + "}" + ("," if n < len(segs) - 1 else ""))
    return "UNWIND [\n" + "\n".join(lines) + f"\n] AS {var}"


def sets(var, props, indent="    "):
    """SET var.k = v, … (one property per line)."""
    items = [f"{var}.{k} = {lit(v)}" for k, v in props.items()]
    return "SET " + f",\n{indent}".join(items)


def merge(var, label, nid, props):
    return f"MERGE ({var}:{label} {{id: {lit(nid)}}})\n" + sets(var, props)


def section(title, *notes):
    body = "\n".join(f"//    {n}" for n in notes)
    return f"\n\n{RULE}\n// {title}\n" + (body + "\n" if notes else "") + RULE + "\n"


def constraint(name, var, label):
    return f"CREATE CONSTRAINT {name} IF NOT EXISTS\nFOR ({var}:{label}) REQUIRE {var}.id IS UNIQUE;"


DEAR = "MATCH (tc:TherapyConcept {id: 'dbt_dear_man'})"


def concept(props):
    return DEAR + "\n" + sets("tc", props) + ";"


