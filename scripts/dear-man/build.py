def build_safety():
    props = {k: v for k, v in C.SAFETY_COPY.items() if k != "id"}
    return f"""{RULE}
// DEAR MAN SAFETY GATES — copy for the band gate in DEAR MAN
{GENERATED}
//
//   dear-man-safety-v3 (A4-4): DEAR MAN no longer asks a 0–10 rating
//   and no longer reads Recover's numeric thresholds. It gates on the
//   capacity band (schema/capacity.cypher: BandRule dear-man:steady
//   full · stirred full + summary heads-up · flooded P2 hand-off),
//   carried from a check-in within 20 minutes (the probe is out since
//   30 Sep). This file holds only the DEAR MAN-specific lines: the
//   carried-over context card, the one-message note and the "still
//   loud" heads-up on the finished plan (shown when the band isn't
//   steady).
//
//   The plan is never locked. Someone who worked through the whole
//   plan while stirred gets a heads-up that it won't land the way they
//   mean it, and an optional 30-second breath to take the edge off.
//   (v1 locked the plan for 20 minutes; that punished the effort and
//   pushed people to send without the plan.)
//
//   handoffSituationId names the DearManSituationType a handoff from
//   "Recover from a hurtful moment" preselects ('address' is defined
//   in dear-man-content.cypher).
//
// All operations use MERGE + SET — safe to re-run.
// Chunked per Aura requirement (no variable persistence).
// Load AFTER dear-man-content.cypher and invalidation-recovery.cypher.
{RULE}


// --- CONSTRAINTS ---
{constraint("dearman_safety_copy_id", "c", "DearManSafetyCopy")}
{section("1. SAFETY COPY", "{emotion} / {need} / {minutes} are filled by the frontend.")}
{merge("c", "DearManSafetyCopy", C.SAFETY_COPY["id"], props)}
REMOVE c.planLocked, c.planUnlocked, c.planLockedHeading;
// The old number-scale copy (intensityQuestion, intensityHint, intensityLow, intensityHigh,
// downshiftLead, rerateQuestion, rerateHint) is no longer set, but stays on the live node for one
// release: a tab still running the pre-M3 page skips DEAR MAN's arousal check without it (Codex,
// PR #17). Remove it in the next content release.
{section("2. LINK TO THE DEAR MAN THERAPY CONCEPT (traceability)")}
MATCH (c:DearManSafetyCopy {{id: 'dear_man_safety_copy'}}), (tc:TherapyConcept {{id: 'dbt_dear_man'}})
MERGE (tc)-[:HAS_SAFETY_COPY]->(c);
"""


BUILD = {"content": build_content, "v2": build_v2, "debrief": build_debrief, "safety": build_safety}


def generated():
    return {path: BUILD[k]() for k, path in FILES.items()}


def main(argv):
    out = generated()
    if "--check" in argv:
        stale = [p for p, text in out.items() if open(os.path.join(ROOT, p), encoding="utf8").read() != text]
        if stale:
            print("stale (run python3 scripts/dear-man/build.py):", ", ".join(stale))
            return 1
        return 0
    if "--prove" in argv:
        ref = argv[argv.index("--prove") + 1]
        bad = 0
        for p, text in out.items():
            old = subprocess.run(["git", "show", f"{ref}:{p}"], cwd=ROOT, capture_output=True, text=True, check=True).stdout
            a, b = tokens(old), tokens(text)
            if a == b:
                print(f"same statements: {p} ({len(a)} tokens)")
                continue
            bad += 1
            i = next((i for i, (x, y) in enumerate(zip(a, b)) if x != y), min(len(a), len(b)))
            print(f"DIFFERENT: {p} at token {i}: {a[i - 3:i + 3]} vs {b[i - 3:i + 3]}")
        return 1 if bad else 0
    for p, text in out.items():
        with open(os.path.join(ROOT, p), "w", encoding="utf8") as f:
            f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
