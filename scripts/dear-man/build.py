def multiline(rows, var):
    """UNWIND rows whose text is long: one key per line."""
    out = []
    for n, r in enumerate(rows):
        items = [f"{k}: {lit(v)}" for k, v in r.items()]
        out.append("  {" + ",\n   ".join(items) + "}" + ("," if n < len(rows) - 1 else ""))
    return "UNWIND [\n" + "\n".join(out) + f"\n] AS {var}"


def build_v2():
    L = [f"""{RULE}
// DEAR MAN CONTENT v2 — Enrichment on top of dear-man-content.cypher
{GENERATED}
//
//   1. Feeling groups (color-coded clusters for the Express step)
//   2. New feeling chips
//   3. Mirroring text ("how this might typically make someone feel")
//      on describe options + situation types, for alexithymia support
//   4. Per-assert-option elaboration prompts
//   5. Anchor needs + a richer, tagged anchor phrase set
//      (powers the "help me find my phrase" generator)
//
// All operations use MERGE — safe to re-run.
// Chunked per Aura requirement (no variable persistence).
// Load AFTER dear-man-content.cypher.
{RULE}


// --- CONSTRAINTS ---
{constraint("dearman_feeling_group_id", "g", "DearManFeelingGroup")}

{constraint("dearman_anchor_need_id", "n", "DearManAnchorNeed")}"""]
    L.append(section("1. FEELING GROUPS", "colorKey is a presentation hint the frontend maps to a theme token."))
    L.append(unwind(C.FEELING_GROUPS, "g") + "\nMERGE (grp:DearManFeelingGroup {id: g.id})\nSET grp.label = g.label, grp.colorKey = g.colorKey, grp.sortOrder = g.sort;")
    L.append(section("2. NEW FEELING CHIPS (existing 18 are in dear-man-content.cypher)"))
    L.append(unwind(C.FEELING_CHIPS_V2, "f") + "\nMERGE (chip:DearManFeelingChip {id: f.id})\nSET chip.label = f.label, chip.sortOrder = f.sort;")
    L.append("\n\n\n// --- Chip → group membership ---\n" + unwind(C.CHIP_GROUPS, "m")
             + "\nMATCH (chip:DearManFeelingChip {id: m.chip})\nMATCH (grp:DearManFeelingGroup {id: m.grp})\nMERGE (chip)-[:IN_GROUP]->(grp);")
    L.append(section("3. MIRRORING — \"how this might typically make someone feel\"",
                     "Per describe option (specific), with a per-situation-type fallback", "used when the user wrote their own description."))
    L.append(multiline(C.MIRROR_DESCRIBE, "m") + "\nMATCH (opt:DearManDescribeOption {id: m.id})\nSET opt.mirrorText = m.text, opt.typicalFeelingIds = m.feelings;")
    L.append("\n\n// --- Situation-type fallback (used when the description is custom) ---\n" + multiline(C.MIRROR_SITUATION, "m")
             + "\nMATCH (s:DearManSituationType {id: m.id})\nSET s.mirrorText = m.text, s.typicalFeelingIds = m.feelings;")
    L.append(section("4. ASSERT ELABORATION PROMPTS"))
    L.append(unwind(C.ASSERT_PROMPTS, "a") + "\nMATCH (opt:DearManAssertOption {id: a.id})\nSET opt.elaboratePrompt = a.prompt;")
    L.append(section("5. ANCHOR NEEDS — \"What do you most need to hear when it gets hard?\"", "Each need is linked to the barriers it most often answers."))
    L.append(unwind(C.ANCHOR_NEEDS, "n") + "\nMERGE (need:DearManAnchorNeed {id: n.id})\nSET need.label = n.label, need.sortOrder = n.sort, need.barrierIds = n.barriers;")
    L.append(section("6. ANCHOR PHRASES — tagged by need + barrier", "(retags the original four, adds the rest)"))
    L.append(unwind(C.ANCHOR_PHRASES, "a") + """
MERGE (p:DearManAnchorPhrase {id: a.id})
SET p.label = a.label, p.sortOrder = a.sort, p.needIds = a.needs, p.barrierIds = a.barriers;

// --- Phrase → need relationships (for traversal) ---
MATCH (p:DearManAnchorPhrase)
WHERE p.needIds IS NOT NULL
UNWIND p.needIds AS needId
MATCH (n:DearManAnchorNeed {id: needId})
MERGE (p)-[:ANSWERS_NEED]->(n);

// --- Phrase → barrier relationships ---
MATCH (p:DearManAnchorPhrase)
WHERE p.barrierIds IS NOT NULL
UNWIND p.barrierIds AS barrierId
MATCH (b:DearManBarrier {id: barrierId})
MERGE (p)-[:HELPS_WITH]->(b);

// --- Generator intro text (stored on the TherapyConcept) ---
""" + concept(C.ANCHOR_GENERATOR))
    return "".join(L) + "\n"


