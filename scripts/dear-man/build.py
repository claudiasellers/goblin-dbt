def build_debrief():
    L = [f"""{RULE}
// DEAR MAN Debrief — Chain Analysis + Cope-Ahead Content
{GENERATED}
// Run with MERGE for idempotency. Safe to re-run.
{RULE}

// ── Constraints ──
"""]
    for var, label in [("tp", "TurningPoint"), ("mr", "MomentResponse"), ("bs", "BodySignal"), ("tp2", "ThoughtPattern"),
                       ("u", "Underneath"), ("r", "Reflection"), ("ca", "CopeAhead")]:
        L.append(f"CREATE CONSTRAINT IF NOT EXISTS FOR ({var}:{label}) REQUIRE {var}.id IS UNIQUE;\n")
    L.append("\n// ── Overall debrief response text on TherapyConcept ──\n\n" + concept(C.DEBRIEF_RESPONSES) + "\n")

    def nodes(title, var, label, rows, note=None):
        head = f"\n// ── {title} ──\n" + (f"// {note}\n" if note else "") + "\n"
        return head + "\n\n".join(merge(var, label, r["id"], {k: v for k, v in r.items() if k != "id"}) + ";" for r in rows) + "\n"

    L.append(nodes("TurningPoint nodes", "tp", "TurningPoint", C.TURNING_POINTS))
    L.append(nodes("MomentResponse nodes", "mr", "MomentResponse", C.MOMENT_RESPONSES, "These represent what the user did IN that turning-point moment."))
    L.append("""
// ── RESPONDS_TO relationships (MomentResponse → TurningPoint) ──
// All MomentResponses can follow any TurningPoint EXCEPT tp_went_okay

MATCH (mr:MomentResponse), (tp:TurningPoint)
WHERE tp.id <> 'tp_went_okay'
MERGE (mr)-[:RESPONDS_TO]->(tp);
""")
    L.append(nodes("BodySignal nodes", "bs", "BodySignal", C.BODY_SIGNALS))
    L.append(nodes("ThoughtPattern nodes", "tp2", "ThoughtPattern", C.THOUGHT_PATTERNS))
    L.append(nodes("Underneath emotion nodes", "u", "Underneath", C.UNDERNEATH))

    L.append("""
// ── Reflection nodes ──
// Keyed to (TurningPoint, MomentResponse) pairs via dual relationships.
// Each block uses MATCH for existing target nodes + MERGE for the relationship.
""")
    for r in C.REFLECTIONS:
        props = {k: v for k, v in r.items() if k not in ("id", "turningPoint", "response")}
        rid = lit(r["id"])
        if r.get("turningPoint"):
            L.append(f"\n// {r['turningPoint']} + {r['response']}\n" + merge("r", "Reflection", r["id"], props) + ";\n")
            L.append(f"\nMATCH (r:Reflection {{id: {rid}}}), (tp:TurningPoint {{id: {lit(r['turningPoint'])}}})\nMERGE (r)-[:REFLECTS_ON]->(tp);\n")
            L.append(f"\nMATCH (r:Reflection {{id: {rid}}}), (mr:MomentResponse {{id: {lit(r['response'])}}})\nMERGE (r)-[:FOR_RESPONSE]->(mr);\n")
        else:
            L.append("\n// Default reflection for any pair without its own\n" + merge("r", "Reflection", r["id"], props) + ";\n")

    L.append("""
// ── CopeAhead nodes ──
// Keyed to MomentResponse via FOR_RESPONSE, plus universals.
""")
    for r in C.COPE_AHEAD:
        props = {k: v for k, v in r.items() if k not in ("id", "responses")}
        L.append("\n" + merge("ca", "CopeAhead", r["id"], props) + ";\n")
        for mr in r["responses"]:
            L.append(f"\nMATCH (ca:CopeAhead {{id: {lit(r['id'])}}}), (mr:MomentResponse {{id: {lit(mr)}}})\nMERGE (ca)-[:FOR_RESPONSE]->(mr);\n")
    L.append(nodes("New DearManFeelingChip nodes for debrief", "f", "DearManFeelingChip", C.DEBRIEF_FEELING_CHIPS))
    L.append("""
// ── TroubleshootFactor nodes (IE-11, Handout 9) ──
// What got in the way most, after an ask that went partly or not at all. SUGGESTS_FACTOR: a turning point that
// often points to the factor (knowledge, not routing). IMPLEMENTS: part of DEAR MAN's debrief.
""")
    for r in C.TROUBLESHOOT_FACTORS:
        props = {k: v for k, v in r.items() if k not in ("id", "suggestedBy")}
        L.append("\n" + merge("tf", "TroubleshootFactor", r["id"], props) + ";\n")
        L.append(f"\nMATCH (tf:TroubleshootFactor {{id: {lit(r['id'])}}}), (tc:TherapyConcept {{id: 'dbt_dear_man'}})\nMERGE (tf)-[:IMPLEMENTS]->(tc);\n")
        for tp in r["suggestedBy"]:
            L.append(f"\nMATCH (tp:TurningPoint {{id: {lit(tp)}}}), (tf:TroubleshootFactor {{id: {lit(r['id'])}}})\nMERGE (tp)-[:SUGGESTS_FACTOR]->(tf);\n")
    return "".join(L)


