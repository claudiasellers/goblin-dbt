"""Generate DEAR MAN's four schema files from content.py (docs/design/dbt-modules-plan.md C5, IE-B1).

  python3 scripts/dear-man/build.py                  # write schema/dear-man-*.cypher
  python3 scripts/dear-man/build.py --check          # exit 1 if a file differs from what content.py generates
  python3 scripts/dear-man/build.py --prove <ref>    # same Cypher tokens as the files at a git ref (the port proof)

The statement shapes are the hand-written files' own, kept token for token (the address block's
`hasPlaceholder = false`, the pattern block's `coalesce`, the anchor phrases' list-to-edge pass), so a
regenerated file sends Neo4j exactly what the hand-written one did. Constraints stay in these files, as before.
"""
