"""Generate schema/find-the-feeling.cypher from content.py (the single editable source).

Usage (repo root; write to a temp file first so a failed build never empties the migration):
  python3 scripts/find-the-feeling/build.py > /tmp/ftf.cypher && mv /tmp/ftf.cypher schema/find-the-feeling.cypher
Then run: node --test tests/find-the-feeling.test.mjs
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from content import *  # noqa: E402,F403

def q(s): return json.dumps(s, ensure_ascii=False)  # Cypher accepts JSON-style double-quoted strings
SHAPE_DIMS = ["sharp", "heat", "weight", "buzz", "clench"]
SOUND_DIMS = ["rough", "grit", "register", "pulse"]

def check():
    seen = set()
    for fid, _, words in FAMILIES:
        for eid, shape, sound in words:
            assert eid not in seen, f"duplicate word {eid}"
            seen.add(eid)
            assert set(shape) <= set(SHAPE_DIMS), (eid, shape)
            assert all(-1 <= v <= 1 for v in shape.values()), eid
            assert len(sound) == 4 and all(0 <= v <= 1 for v in sound), eid
    assert {u[0] for u in URGES} == {"fight", "chase", "hide", "blank"}
check()

L = []
A = L.append
A("""// ============================================================
// FIND THE FEELING ("Shape it" / "Tune it") — find-v1
// GENERATED by scripts/find-the-feeling/build.py from content.py. Edit content.py, not this file.
// Emotion identification for alexithymia without rating scales: match the feeling to a shape or a
// sound, then accept or refuse an offered word. Word signatures hang off existing Emotion nodes.
// Run AFTER invalidation-recovery.cypher (reuses ClinicalSource linehan_skills_2015 and
// TherapyConcept affect_labeling). Idempotent: MERGE + SET only, constraints IF NOT EXISTS.
// See docs/design/find-the-feeling.md.
// ============================================================
""")
for c in ["feeling_signature_id:FeelingSignature", "feeling_family_id:FeelingFamily", "feeling_urge_id:FeelingUrge"]:
    n, lab = c.split(":")
    A(f"CREATE CONSTRAINT {n} IF NOT EXISTS\nFOR (n:{lab}) REQUIRE n.id IS UNIQUE;")
A("CREATE CONSTRAINT find_the_feeling_session_key IF NOT EXISTS\nFOR (s:FindTheFeelingSession) REQUIRE s.key IS UNIQUE;\n")

A("// --- Therapy concepts ---")
for id_, name, desc, mod, module, parent in NEW_CONCEPTS:
    A(f"MERGE (c:TherapyConcept {{id: {q(id_)}}})\nSET c.name = {q(name)}, c.description = {q(desc)}, c.modality = {q(mod)}" + (f", c.module = {q(module)}" if module else "") + ";")
    if parent:
        rel, target = ("RELATED_TO", parent[4:]) if parent.startswith("rel:") else ("PART_OF", parent)
        A(f"MATCH (c:TherapyConcept {{id: {q(id_)}}}), (m:TherapyConcept {{id: {q(target)}}})\nMERGE (c)-[:{rel}]->(m);")
A("MATCH (t:TherapyConcept {id: 'dbt_find_the_feeling'})\nSET t.whenToUse = \"When you can tell something's there but not what it is\", t.dbtBasis = 'Emotion Regulation: observing, describing and naming emotions (with Mindfulness Describe), without numeric rating';")
A("MATCH (:TherapyConcept {id: 'dbt_find_the_feeling'})-[r:USES|ADDRESSES]->() DELETE r;")
A(f"UNWIND {q(USES)} AS cid\nMATCH (t:TherapyConcept {{id: 'dbt_find_the_feeling'}}), (c:TherapyConcept {{id: cid}})\nMERGE (t)-[:USES]->(c);")
A(f"UNWIND {q(ADDRESSES)} AS eid\nMATCH (t:TherapyConcept {{id: 'dbt_find_the_feeling'}}), (e:Emotion {{id: eid}})\nMERGE (t)-[:ADDRESSES]->(e);")

A("\n// --- App tool ids (join key for the frontend; replaces guessing via normalizeToolId) ---")
rows = "[" + ", ".join("{c: %s, t: %s}" % (q(c), q(t)) for c, t in APP_TOOL_IDS.items()) + "]"
A(f"UNWIND {rows} AS row\nMATCH (c:TherapyConcept {{id: row.c}})\nSET c.appToolId = row.t;")

A("\n// --- Clinical sources ---")
for id_, title, url in SOURCES:
    A(f"MERGE (s:ClinicalSource {{id: {q(id_)}}})\nSET s.title = {q(title)}, s.url = {q(url)};")

A("\n// --- Feeling families and word signatures (hypotheses to offer, not to diagnose) ---")
A("MATCH (:FeelingFamily)-[r:INCLUDES]->() DELETE r;")
for fi, (fid, label, words) in enumerate(FAMILIES):
    A(f"MERGE (f:FeelingFamily {{id: {q(fid)}}})\nSET f.label = {q(label)}, f.order = {fi};")
    for wi, (eid, shape, sound) in enumerate(words):
        sid = f"sig_{eid}"
        sv = [float(shape.get(d, 0)) for d in SHAPE_DIMS]
        A(f"MATCH (e:Emotion {{id: {q(eid)}}})\nMERGE (g:FeelingSignature {{id: {q(sid)}}})\n"
          f"SET g.shape = {q(sv)}, g.sound = {q([float(x) for x in sound])}, g.shapeDims = {q(SHAPE_DIMS)}, g.soundDims = {q(SOUND_DIMS)},\n"
          f"    g.evidenceGrade = 'Preliminary', g.reviewStatus = 'needs_clinical_review'\n"
          f"MERGE (e)-[:HAS_FEELING_SIGNATURE]->(g)\n"
          f"WITH g\nMATCH (f:FeelingFamily {{id: {q(fid)}}})\nMERGE (f)-[r:INCLUDES]->(g) SET r.offer = {wi};")

A("\n// --- Urges and where they route ---")
A("MATCH (:FeelingUrge)-[r:ROUTES_TO]->() DELETE r;")
for i, (uid, label, sub, routes) in enumerate(URGES):
    A(f"MERGE (u:FeelingUrge {{id: {q(uid)}}})\nSET u.label = {q(label)}, u.sub = {q(sub)}, u.order = {i};")
    rows = "[" + ", ".join("{c: %s, rank: %d}" % (q(c), r) for c, r in routes) + "]"
    A(f"UNWIND {rows} AS row\nMATCH (u:FeelingUrge {{id: {q(uid)}}}), (c:TherapyConcept {{id: row.c}})\nMERGE (u)-[r:ROUTES_TO]->(c) SET r.rank = row.rank;")

A("\n// --- Flow document (copy + gates), versioned like InvalidationRecoveryFlow ---")
A(f"MERGE (f:FindTheFeelingFlow {{id: 'find_the_feeling_flow'}})\nSET f.version = {q(FLOW['version'])}, f.contentJson = {q(json.dumps(FLOW, ensure_ascii=False))};")
A(f"MATCH (f:FindTheFeelingFlow {{id: 'find_the_feeling_flow'}}), (s:ClinicalSource)\nWHERE s.id IN {q(FLOW['sourceIds'])}\nMERGE (f)-[:GROUNDED_IN]->(s);")
A("MATCH (f:FindTheFeelingFlow {id: 'find_the_feeling_flow'}), (t:TherapyConcept {id: 'dbt_find_the_feeling'})\nMERGE (t)-[:IMPLEMENTED_BY_FLOW]->(f);")
A("MATCH (f:FindTheFeelingFlow {id: 'find_the_feeling_flow'}), (u:FeelingUrge)\nMERGE (f)-[:INCLUDES_URGE]->(u);")
A("MATCH (f:FindTheFeelingFlow {id: 'find_the_feeling_flow'}), (fam:FeelingFamily)\nMERGE (f)-[:INCLUDES_FAMILY]->(fam);")
A("\nCREATE INDEX find_the_feeling_session_created IF NOT EXISTS\nFOR (s:FindTheFeelingSession) ON (s.createdAt);")
print("\n".join(L))
