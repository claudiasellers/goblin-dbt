"""Generate schema/capacity.cypher from content.py (the single editable source).

Usage (repo root; write to a temp file first so a failed build never empties the file):
  python3 scripts/capacity/build.py > /tmp/cap.cypher && mv /tmp/cap.cypher schema/capacity.cypher
Then run: node --test tests/capacity-content.test.mjs
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from content import *  # noqa: E402,F403

def q(s): return json.dumps(s, ensure_ascii=False)  # Cypher accepts JSON-style double-quoted strings
def js(o): return q(json.dumps(o, ensure_ascii=False))

def check():
    assert list(BAND_INTENSITY) == BANDS and list(PROBE_DEFAULT["options"]) == BANDS
    assert list(PROBE_RELATIONAL["options"]) == BANDS
    assert list(HANDOFF["reread"]["options"]) == THEN_VS_NOW
    assert {p[0] for p in PRIMITIVES} == {"sigh", "orient"}
    for skill, _, band, mode, _ in BAND_RULES:
        assert band in BANDS and mode in ("full", "short", "handoff", "notOffered"), (skill, band)
    assert "!" not in json.dumps(HANDOFF) + json.dumps(PROBE_RELATIONAL)
check()

CONTENT = {
    "version": VERSION,
    "freshMinutes": FRESH_MINUTES,
    "bandIntensity": BAND_INTENSITY,
    "probe": {"wordings": {"default": PROBE_DEFAULT, "relational": PROBE_RELATIONAL}, "cantTell": CANT_TELL},
    "handoff": HANDOFF,
}

L = []
A = L.append
A(f"""// ============================================================
// CAPACITY BAND (ER-01) — {VERSION} (plan A4-1)
// GENERATED by scripts/capacity/build.py from content.py. Edit content.py, not this file.
// The relational capacity probe (steady · stirred · flooded) that replaces 0–10 scales, the
// breakdown hand-off primitives (interim: Recover's sigh, FTF's orient) and the band rules
// Phase A reads (DEAR MAN). A reading is a value object stored on the log record that asked
// (CheckIn / ToolSession), never a node (ruling R1).
// Run AFTER invalidation-recovery.cypher (cyclic_sighing, linehan_skills_2015). Idempotent:
// MERGE + SET only; constraints live in constraints.cypher. Copy is reviewStatus "{REVIEW_STATUS}".
// ============================================================
""")

A("// --- Clinical sources ---")
for id_, title, url in SOURCES:
    A(f"MERGE (s:ClinicalSource {{id: {q(id_)}}})\nSET s.title = {q(title)}, s.url = {q(url)};")

A("\n// --- The probe (+ hand-off copy and band → intensity compatibility) ---")
A(f"MERGE (p:CapacityProbe {{id: 'capacity_probe'}})\nSET p.version = {q(VERSION)}, p.freshMinutes = {FRESH_MINUTES}, p.reviewStatus = {q(REVIEW_STATUS)}, p.contentJson = {js(CONTENT)};")
A("MATCH (p:CapacityProbe {id: 'capacity_probe'}), (m:StateModulator {id: 'acute_stress_catecholamine'})\nMERGE (m)-[:INFORMS]->(p);")
A(f"MATCH (p:CapacityProbe {{id: 'capacity_probe'}}), (s:ClinicalSource)\nWHERE s.id IN {q(PROBE_SOURCE_IDS)}\nMERGE (p)-[:GROUNDED_IN]->(s);")

A("\n// --- Hand-off primitives (interim; DT-01 adds dt.regulate rows without a contract change) ---")
A("MATCH (:HandoffPrimitive)-[r:IMPLEMENTS]->() DELETE r;")
for pid, comp, direction, bands, blank, rank, concept, copy in PRIMITIVES:
    A(f"MERGE (h:HandoffPrimitive {{id: {q(pid)}}})\nSET h.component = {q(comp)}, h.direction = {q(direction)}, h.bands = {q(bands)},"
      f" h.blank = {q(blank)}, h.rank = {rank}, h.conceptId = {q(concept)}, h.copyJson = {js(copy)};")
    A(f"MATCH (h:HandoffPrimitive {{id: {q(pid)}}}), (c:TherapyConcept {{id: {q(concept)}}})\nMERGE (h)-[:IMPLEMENTS]->(c);")

A("\n// --- Band rules (Phase A: DEAR MAN only) ---")
A("MATCH (:BandRule)-[r:FOR_SKILL]->() DELETE r;")
for skill, concept, band, mode, heads_up in BAND_RULES:
    rid = f"{skill}:{band}"
    copy = {"headsUp": heads_up} if heads_up else {}
    A(f"MERGE (r:BandRule {{id: {q(rid)}}})\nSET r.skillId = {q(skill)}, r.band = {q(band)}, r.mode = {q(mode)}, r.copyJson = {js(copy)};")
    A(f"MATCH (r:BandRule {{id: {q(rid)}}}), (tc:TherapyConcept {{id: {q(concept)}}})\nMERGE (r)-[:FOR_SKILL]->(tc);")
A("MATCH (m:StateModulator {id: 'acute_stress_catecholamine'}), (r:BandRule)\nMERGE (m)-[:INFORMS]->(r);")
print("\n".join(L))
