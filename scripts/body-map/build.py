"""Generate schema/body-map.cypher from content.py (the single editable source).

Usage (repo root; write to a temp file first so a failed build never empties the file):
  python3 scripts/body-map/build.py > /tmp/bm.cypher && mv /tmp/bm.cypher schema/body-map.cypher
Then: python3 scripts/body-map/fixture.py && node --test tests/body-map-content.test.mjs
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from content import VERSION, SIGNED_OFF, REGIONS, REGION_NAMES, ZONES, PAD_WORDS, FELT, MAPS, BASE, NEW  # noqa: E402
from places import felt_status, places_for  # noqa: E402


def q(s): return json.dumps(s, ensure_ascii=False)  # Cypher accepts JSON-style double-quoted strings


def status(key):
    """(status, reviewStatus, reviewedAt): live only once signed off."""
    return ("live", "reviewed", SIGNED_OFF[key]) if key in SIGNED_OFF else ("draft", "draft", None)


def check():
    words = {w[0]: w for w in PAD_WORDS}
    assert len(words) == len(PAD_WORDS), "duplicate pad word id"
    assert list(REGION_NAMES) == REGIONS, "REGION_NAMES must list REGIONS in order"
    for wid, label, zones, regions, energy in PAD_WORDS:
        assert zones and set(zones) <= set(ZONES), wid
        assert regions is None or (regions and set(regions) <= set(REGIONS)), wid
        assert energy in ("more", "less"), wid
        assert label and "!" not in label and label[0].isupper(), wid
    # Every place on the figure has at least one pad word in every quarter of the pad.
    for region in REGIONS:
        for zone in ZONES:
            assert any(zone in z and (r is None or region in r) for _, _, z, r, _ in PAD_WORDS), (region, zone)
    felt_keys = set()
    for e, rows in FELT.items():
        seen = set()
        for region, sid, weight, origin in rows:
            assert region in REGIONS and sid in words, (e, region, sid)
            allowed = words[sid][3]
            assert allowed is None or region in allowed, f"{sid} isn't offered at {region} ({e})"
            assert 0 < weight <= 1 and origin in (BASE, NEW), (e, region, sid)
            assert (region, sid) not in seen, f"{e}: {region} {sid} twice"
            seen.add((region, sid))
            if origin == NEW:
                felt_keys.add(f"felt:{e}:{region}:{sid}")
    owner = {}
    for mid, (label, groups, grid_words) in MAPS.items():
        assert groups and len(set(groups)) == len(groups), mid
        assert len(places_for(mid, ("live", "draft"))) >= 3, f"{mid}: fewer than 3 places"
        for w in grid_words:
            assert w not in owner, f"{w} mirrors both {owner[w]} and {mid}"
            owner[w] = mid
    for e in FELT:
        assert any(e in g for _, g, _ in MAPS.values()), f"{e} has FELT_AS rows but no map groups it"
    unknown = {k for k in SIGNED_OFF
               if not (k.startswith("map:") and k[4:] in MAPS)
               and not (k.startswith("word:") and k[5:] in words)
               and k not in felt_keys}
    assert not unknown, unknown


check()

L = []
A = L.append
A(f"""// ============================================================
// BODY MAP — {VERSION} (docs/design/body-map.md)
// GENERATED by scripts/body-map/build.py from content.py. Edit content.py, not this file.
//   BodyRegion        the 15 places the body step uses.
//   SensationType     + padLabel / zones / regions / energy (the sensation chips).
//   FELT_AS           (Emotion)-[:FELT_AS {{region, weight, status}}]->(SensationType): where each emotion
//                     is felt. The ONE source of that knowledge; rows not in content.py are removed.
//   BodyMap           a family of feelings: -[:GROUPS]-> the emotions whose FELT_AS give its places
//                     (computed by getBodyMapContent, never stored) and -[:MIRRORS]-> the grid words
//                     (Emotion nodes from emotion-wheel-sync) it answers.
// Only status "live" is served; drafts are loaded but never served.
// Run AFTER knowledge-graph.cypher (SensationType, Emotion) and emotion-wheel-sync.cypher (grid
// words). Idempotent: MERGE + SET, removed rows pruned by id; constraints live in constraints.cypher.
// ============================================================
""")

A(f"MERGE (c:BodyMapContent {{id: 'body_map'}})\nSET c.version = {q(VERSION)}, c.regions = {q(REGIONS)};")

A("\n// --- Body regions (the 15 places) ---")
for rank, (rid, (name, includes)) in enumerate(REGION_NAMES.items()):
    A(f"MERGE (r:BodyRegion {{id: {q(rid)}}})\nSET r += {{name: {q(name)}, includes: {q(includes)}, rank: {rank}}};")
A(f"MATCH (r:BodyRegion) WHERE NOT r.id IN {q(REGIONS)}\nDETACH DELETE r;")

# SensationType ids already in knowledge-graph.cypher: they keep their own `name`.
EXISTING_SENSATIONS = {"tension", "heaviness", "lightness", "heat", "cold_sensation", "numbness_sensation", "pressure",
                       "butterflies", "racing_heart", "constriction", "expansion", "shaking", "weakness", "restlessness",
                       "groundedness"}

A("\n// --- Pad words (SensationType) ---")
for rank, (wid, label, zones, regions, energy) in enumerate(PAD_WORDS):
    st, rv, at = status("word:" + wid)
    A(f"MERGE (s:SensationType {{id: {q(wid)}}})\n"
      f"SET s += {{padLabel: {q(label)}, zones: {q(zones)}, regions: {q(regions or [])}, energy: {q(energy)}, padRank: {rank},"
      f" padStatus: {q(st)}, padReviewStatus: {q(rv)}, padReviewedAt: {q(at)}"
      + ("" if wid in EXISTING_SENSATIONS else f", name: {q(label)}") + "};")
A("\n// --- Retire pad words removed from content.py (the SensationType stays) ---")
A(f"MATCH (s:SensationType) WHERE s.padStatus IS NOT NULL AND NOT s.id IN {q([w[0] for w in PAD_WORDS])}\nSET s.padStatus = 'retired';")

A("\n// --- FELT_AS: where each emotion is felt ---")
felt_ids = []
for e, rows in FELT.items():
    for region, sid, weight, origin in rows:
        st = felt_status(e, region, sid, origin)
        key = f"felt:{e}:{region}:{sid}"
        at = SIGNED_OFF.get(key)
        felt_ids.append(f"{e}:{region}:{sid}")
        A(f"MATCH (e:Emotion {{id: {q(e)}}}), (s:SensationType {{id: {q(sid)}}})\n"
          f"MERGE (e)-[r:FELT_AS {{region: {q(region)}}}]->(s)\n"
          f"SET r += {{weight: {weight}, status: {q(st)}, origin: {q(origin)}, reviewedAt: {q(at)}}};")
A("\n// --- Remove FELT_AS rows that are no longer in content.py (incl. the old region \"back\") ---")
A(f"MATCH (e:Emotion)-[r:FELT_AS]->(s:SensationType) WHERE NOT (e.id + ':' + r.region + ':' + s.id) IN {q(felt_ids)}\nDELETE r;")

A("\n// --- Body maps (the mirror): which emotions they group, which grid words they mirror ---")
for rank, (mid, (label, groups, grid_words)) in enumerate(MAPS.items()):
    st, rv, at = status("map:" + mid)
    A(f"MERGE (m:BodyMap {{id: {q(mid)}}})\n"
      f"SET m += {{label: {q(label)}, rank: {rank}, status: {q(st)}, reviewStatus: {q(rv)}, reviewedAt: {q(at)}, version: {q(VERSION)}}}\n"
      f"REMOVE m.wordIds;")
    A(f"MATCH (m:BodyMap {{id: {q(mid)}}}), (e:Emotion) WHERE e.id IN {q(groups)}\nMERGE (m)-[:GROUPS]->(e);")
    A(f"MATCH (m:BodyMap {{id: {q(mid)}}})-[r:GROUPS]->(e:Emotion) WHERE NOT e.id IN {q(groups)}\nDELETE r;")
    A(f"MATCH (m:BodyMap {{id: {q(mid)}}}), (w:Emotion) WHERE w.id IN {q(grid_words)}\nMERGE (m)-[:MIRRORS]->(w);")
    A(f"MATCH (m:BodyMap {{id: {q(mid)}}})-[r:MIRRORS]->(w:Emotion) WHERE NOT w.id IN {q(grid_words)}\nDELETE r;")

A("\n// --- Prune maps removed from content.py, and the places maps used to store (body-map-v1) ---")
A(f"MATCH (m:BodyMap) WHERE NOT m.id IN {q(list(MAPS))}\nDETACH DELETE m;")
A("MATCH (p:BodyMapPlace)\nDETACH DELETE p;")
print("\n".join(L))
