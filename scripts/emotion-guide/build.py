"""Regenerate schema/emotion-guide.cypher from scripts/emotion-guide/content.py (the one editable source).

  python3 scripts/emotion-guide/build.py           # write the file
  python3 scripts/emotion-guide/build.py --check   # exit 1 if the file is stale

Checks (ER-10 runtime pins): every ladder word is a grid word of the guide's own family, in order, used once; every
guide but happiness names a DBT parent that has EmotionRegulationContent; happiness words are grid words with no
parent (so parentOf never changes); held urges are that parent's emotion urges; a body map is a signed-off map.
The card's function line and prompts sit in `contentJson`, so the voice lint reads them as flow copy.
"""
import importlib.util
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import content as C  # noqa: E402

OUT = os.path.join(ROOT, "schema/emotion-guide.cypher")
PARENTS = ["fear", "anger", "sadness", "disgust", "shame", "guilt", "jealousy", "envy", "love"]


def _load(name, rel):
    spec = importlib.util.spec_from_file_location(name, os.path.join(ROOT, rel))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def q(s):
    return json.dumps(s, ensure_ascii=False)


def js(o):
    return q(json.dumps(o, ensure_ascii=False, sort_keys=True))


def check():
    sys.path.insert(0, os.path.join(ROOT, "scripts/skills"))
    import graph_tables  # noqa: E402
    parent_of = graph_tables.tables()[0]
    emotions = _load("eg_emotions", "scripts/emotions/content.py")
    grid = [w[0] for w in emotions.SQUARE if isinstance(w, tuple)]
    body = _load("eg_body", "scripts/body-map/content.py")
    oa = _load("eg_oa", "scripts/opposite-action/content.py")
    urges = {p: {u["id"] for u in us} for p, us in oa.PARENT_URGES}
    ids = [g[0] for g in C.GUIDES]
    assert len(set(ids)) == len(ids), "one guide per family"
    assert set(ids) == set(PARENTS) | {"happiness"}, "the nine DBT parents and happiness"
    for w in C.HAPPINESS_WORDS:
        assert w in grid, (w, "a happiness word is a grid word")
        assert w not in parent_of, (w, "a happiness word has no DBT parent: parentOf must not change")
    assert len(set(C.HAPPINESS_WORDS)) == len(C.HAPPINESS_WORDS)
    family = lambda gid: set(C.HAPPINESS_WORDS) if gid == "happiness" else {w for w, p in parent_of.items() if p == gid}  # noqa: E731
    for gid, label, function, prompts, ladder, body_map, held in C.GUIDES:
        assert label and function and 2 <= len(prompts) <= 4, gid
        assert len(ladder) != 1, (gid, "a ladder has two words or more, or none")
        assert len(set(ladder)) == len(ladder), (gid, "no word twice on a ladder")
        for w in ladder:
            assert w in grid, (gid, w, "ladder words are grid words")
            assert w in family(gid), (gid, w, "ladder words are the family's own")
        # Milder to stronger is the content's order (a reviewed judgement, not the square's energy axis).
        if body_map is not None:
            assert f"map:{body_map}" in body.SIGNED_OFF, (gid, body_map, "a signed-off body map")
        for u in held:
            assert u in urges.get(gid, set()), (gid, u, "a held urge is the parent's own emotion urge")
        assert gid != "happiness" or not held


HEADER = """// ============================================================
// KNOW THIS FEELING (ER-10): the feeling guide (docs/design/emotion-guide.md).
//
// GENERATED by scripts/emotion-guide/build.py from scripts/emotion-guide/content.py: edit content.py, never
// this file.
//
// FeelingGuide, one per DBT emotion family:
//   GUIDES    -> EmotionRegulationContent  (the nine parents; urges via its HAS_ACTION_URGE, words via parentOf)
//   FELT_LIKE -> BodyMap                   (the card's body places: that map's signed-off FELT_AS rows)
//   Emotion -[:IN_GUIDE]-> FeelingGuide     (happiness words only: happiness has no EmotionRegulationContent)
// Read by getSkillContent as the skill runtime's feelingOf / feelingGuideOf tables.
// All MERGE; safe to re-run. Needs emotion-wheel-sync, emotion-regulation-content, opposite-action-data, body-map.
// ============================================================
"""


def generated():
    check()
    out = [HEADER]
    for rank, (gid, label, function, prompts, ladder, body_map, held) in enumerate(C.GUIDES):
        props = {"label": label, "rank": rank, "ladder": ladder, "urgesHeld": sorted(held), "version": C.VERSION}
        body = ", ".join(f"{k}: {q(v)}" for k, v in props.items())
        out += [f"// --- {label} ---",
                f"MERGE (g:FeelingGuide {{id: {q(gid)}}})",
                f"SET g += {{{body}}}, g.contentJson = {js({'function': function, 'prompts': prompts})};"]
        if gid != "happiness":
            out += [f"MATCH (g:FeelingGuide {{id: {q(gid)}}}), (c:EmotionRegulationContent {{dbtParent: {q(gid)}}})",
                    "MERGE (g)-[:GUIDES]->(c);"]
        if body_map:
            out += [f"MATCH (g:FeelingGuide {{id: {q(gid)}}}), (m:BodyMap {{id: {q(body_map)}}})",
                    "MERGE (g)-[:FELT_LIKE]->(m);"]
        out.append("")
    out.append("// --- Happiness words (no DBT parent, so no HAS_REGULATION_CONTENT) ---")
    for w in C.HAPPINESS_WORDS:
        out += [f"MATCH (e:Emotion {{id: {q(w)}}}), (g:FeelingGuide {{id: \"happiness\"}})", "MERGE (e)-[:IN_GUIDE]->(g);"]
    return "\n".join(out) + "\n"


def main(argv):
    text = generated()
    if "--check" in argv:
        cur = open(OUT, encoding="utf8").read() if os.path.exists(OUT) else ""
        if cur != text:
            print("schema/emotion-guide.cypher is stale: run python3 scripts/emotion-guide/build.py", file=sys.stderr)
            return 1
        return 0
    open(OUT, "w", encoding="utf8").write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
