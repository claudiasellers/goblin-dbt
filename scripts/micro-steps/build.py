"""Generate schema/micro-steps.cypher from content.py (the single editable source).

Usage (repo root; write to a temp file first so a failed build never empties the file):
  python3 scripts/micro-steps/build.py > /tmp/ms.cypher && mv /tmp/ms.cypher schema/micro-steps.cypher
  python3 scripts/micro-steps/fixture.py --ship
  python3 scripts/micro-steps/build.py --check   # exits 1 when schema/micro-steps.cypher is stale
"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from content import VERSION, MODALITIES, CRISIS_STATES, SETS  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "schema", "micro-steps.cypher")
# The engine's patterns (functions/src/recommendation/; the 10 ActivationPattern nodes in knowledge-graph.cypher).
PATTERNS = {"acute_alarm", "chronic_vigilance", "emotional_flooding", "social_threat_shame", "reactive_aggression",
            "conservation_freeze", "dissociation_overmodulation", "rumination_loop", "reward_drive_low", "grief_yearning"}


def q(s): return json.dumps(s, ensure_ascii=False)  # Cypher accepts JSON-style double-quoted strings


def check():
    assert set(SETS) == PATTERNS | set(CRISIS_STATES), ("a set for every pattern, and every crisis state", set(SETS) ^ (PATTERNS | set(CRISIS_STATES)))
    ids = [s[0] for v in SETS.values() for s in v]
    assert len(ids) == len(set(ids)), "step ids are unique"
    kg = open(os.path.join(ROOT, "schema", "knowledge-graph.cypher"), encoding="utf8").read()
    for p in PATTERNS:
        assert re.search(rf"ActivationPattern \{{id: ['\"]{p}['\"]", kg), ("a graph pattern", p)
    for sid, steps in SETS.items():
        assert 3 <= len(steps) <= 5, (sid, "3 to 5 steps, so the rotation doesn't repeat")
        assert any(not s[4] for s in steps), (sid, "at least one needs nothing (skipEnvironmental)")
        for i, text, sub, modality, env in steps:
            assert re.fullmatch(r"[a-z]{2}-\d", i), i
            assert len(text.split()) <= 8, (i, "at most 8 words in the main instruction")
            assert modality in MODALITIES, (i, modality)
            assert isinstance(env, bool), i
            assert sub is None or len(sub) <= 60, (i, "the subtext is one short line")
check()


def build():
    L = []
    A = L.append
    A(f"""// ============================================================
// MICRO-STEPS — {VERSION}
// GENERATED by scripts/micro-steps/build.py from content.py. Edit content.py, not this file.
// The lowest-difficulty interventions (DT-01 part 2, docs/design/first-the-body.md): served on *That feels like
// too much right now* and Help me now. Intervention {{kind: 'micro_step'}} nodes, ROUTES_TO {{order}} from the
// ActivationPattern they're for, or from a CrisisState (`fallback`). Run AFTER knowledge-graph.cypher (the
// patterns). Idempotent: MERGE + SET += only; constraints live in constraints.cypher.
// ============================================================
""")
    for cid, why in CRISIS_STATES.items():
        A(f"MERGE (c:CrisisState {{id: {q(cid)}}})\nSET c += {{description: {q(why)}, version: {q(VERSION)}}};")
    A("")
    for sid, steps in SETS.items():
        src = "ActivationPattern" if sid in PATTERNS else "CrisisState"
        A(f"// --- {sid} ---")
        for order, (i, text, sub, modality, env) in enumerate(steps):
            props = {"kind": "micro_step", "text": text, "subtext": sub, "modality": modality, "requiresEnvironment": env, "version": VERSION}
            body = ", ".join(f"{k}: {q(v) if not isinstance(v, bool) else str(v).lower()}" for k, v in props.items() if v is not None)
            A(f"MERGE (n:Intervention {{id: {q(i)}}})\nSET n += {{{body}}};")
            A(f"MATCH (p:{src} {{id: {q(sid)}}}), (n:Intervention {{id: {q(i)}}})\nMERGE (p)-[r:ROUTES_TO]->(n)\nSET r += {{order: {order}}};")
        A("")
    return "\n".join(L).rstrip() + "\n"


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        sys.exit(0 if open(OUT, encoding="utf8").read() == text else 1)
    sys.stdout.write(text)
