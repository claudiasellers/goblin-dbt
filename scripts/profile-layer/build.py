"""Generate schema/profile-layer.cypher from content.py (the single editable source).

Usage (repo root; write to a temp file first so a failed build never empties the file):
  python3 scripts/profile-layer/build.py > /tmp/pl.cypher && mv /tmp/pl.cypher schema/profile-layer.cypher
Then run: node --test tests/profile-layer.test.mjs
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from content import *  # noqa: E402,F403

def q(s): return json.dumps(s, ensure_ascii=False)

def check():
    area_ids = [a[0] for a in AREAS]
    assert len(area_ids) == 7 and len(set(area_ids)) == 7
    for k in KINDS:
        assert k[1] in area_ids, k[0]
    for r in RULES:
        assert r["patternKind"] in [k[0] for k in KINDS], r["id"]
        assert r["minEvidence"] <= r["ofLast"]
    assert "!" not in json.dumps([AREAS, KINDS, RULES])
check()

L = []
A = L.append
A(f"""// ============================================================
// PROFILE LAYER — {VERSION} (PR-P1)
// GENERATED by scripts/profile-layer/build.py from content.py. Edit content.py, not this file.
// The Me areas, profile kinds ("still true?" copy + revisit policy) and pattern-offer rules.
// What a tool may READ is declared in code (functions/src/profile/slices.ts), never here.
// Idempotent: MERGE + SET only; constraints live in constraints.cypher. Copy is "{REVIEW_STATUS}".
// ============================================================
""")
A("// --- Areas ---")
for i, (aid, label, blurb) in enumerate(AREAS):
    A(f"MERGE (a:ProfileArea {{id: {q(aid)}}})\nSET a.label = {q(label)}, a.blurb = {q(blurb)}, a.order = {i}, a.reviewStatus = {q(REVIEW_STATUS)};")
A("\n// --- Kinds ---")
A("MATCH (:ProfileKind)-[r:IN_AREA]->() DELETE r;")
for kid, area, label, days, still, aside in KINDS:
    A(f"MERGE (k:ProfileKind {{id: {q(kid)}}})\nSET k.area = {q(area)}, k.label = {q(label)}, k.revisitAfterDays = {days if days is not None else 'null'},"
      f" k.stillTrueCopy = {q(still)}, k.setAsideCopy = {q(aside)}, k.reviewStatus = {q(REVIEW_STATUS)};")
    A(f"MATCH (k:ProfileKind {{id: {q(kid)}}}), (a:ProfileArea {{id: {q(area)}}})\nMERGE (k)-[:IN_AREA]->(a);")
A("\n// --- Pattern rules (enabled false until reviewed on real data, D-10) ---")
for r in RULES:
    A(f"MERGE (p:PatternRule {{id: {q(r['id'])}}})\nSET p.patternKind = {q(r['patternKind'])}, p.windowDays = {r['windowDays']}, p.minEvidence = {r['minEvidence']},"
      f" p.ofLast = {r['ofLast']}, p.cooldownDays = {r['cooldownDays']}, p.enabled = {str(r['enabled']).lower()},"
      f" p.statementTemplate = {q(r['statementTemplate'])}, p.offerCopy = {q(r['offerCopy'])}, p.reviewStatus = {q(REVIEW_STATUS)};")
print("\n".join(L))
