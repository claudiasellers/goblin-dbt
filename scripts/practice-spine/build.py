"""Generate schema/practice-spine.cypher from content.py (the single editable source).

Usage (repo root; write to a temp file first so a failed build never empties the file):
  python3 scripts/practice-spine/build.py > /tmp/ps.cypher && mv /tmp/ps.cypher schema/practice-spine.cypher
Then run: node --test tests/practice-spine-content.test.mjs
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from content import *  # noqa: E402,F403

def q(s): return json.dumps(s, ensure_ascii=False)  # Cypher accepts JSON-style double-quoted strings
def js(o): return q(json.dumps(o, ensure_ascii=False, sort_keys=True))

TIERS = {"safety", "practice", "quality", "skills"}
MODES = {"inline", "deeplink"}

def check():
    ids = [t["id"] for t in FOLLOW_UP_TYPES]
    assert len(ids) == len(set(ids)), "duplicate FollowUpType id"
    for t in FOLLOW_UP_TYPES:
        assert t["tier"] in TIERS and t["resolveMode"] in MODES, t["id"]
        assert (t["resolveMode"] == "deeplink") == bool(t.get("deepLinkTemplate")), t["id"]
        for c in t["choices"]:
            assert ("status" in c) != ("snoozeHours" in c) or t["id"] == "pattern_offer" or t["id"] == "profile_revisit", (t["id"], c)
            assert c.get("thenVsNow") in (None, *THEN_VS_NOW), (t["id"], c)
        assert "!" not in json.dumps(t["copy"]) + t["notification"], t["id"]
    for kind, k in CLOSE_FLOW["kinds"].items():
        if "dir" in k:
            assert [c["id"] for c in k["choices"]] == THEN_VS_NOW, kind
        if kind == "urge":
            assert all(c["id"] in ACTED_ON_URGE for c in k["choices"]), kind
    assert set(CLOSE_KIND_DIR) <= set(CLOSE_FLOW["kinds"])
check()

L = []
A = L.append
A(f"""// ============================================================
// PRACTICE SPINE CONTENT — {VERSION} (PR-S2)
// GENERATED by scripts/practice-spine/build.py from content.py. Edit content.py, not this file.
// FollowUpType registry, the SessionCloseFlow question (then-vs-now per direction, ruling R3),
// and the PracticeSkill fields the shared rep log needs (defaultFor, displayLabel, 2 new skills).
// All copy is reviewStatus "{REVIEW_STATUS}" until Claudia signs it off.
// Run AFTER find-the-feeling.cypher (TherapyConcept urge_surfing). Idempotent: MERGE + SET only;
// constraints live in constraints.cypher. Never deletes another module's PracticeSkill links.
// ============================================================
""")

A("// --- Session close question (one node; per closeKind copy) ---")
A(f"MERGE (f:SessionCloseFlow {{id: 'session_close'}})\nSET f.version = {q(VERSION)}, f.reviewStatus = {q(REVIEW_STATUS)}, f.contentJson = {js(CLOSE_FLOW)};")

A("\n// --- Follow-up types ---")
for t in FOLLOW_UP_TYPES:
    content = {"copy": t["copy"], "choices": t["choices"], "window": t["window"], "notification": t["notification"]}
    if t.get("dir"): content["dir"] = t["dir"]
    A(f"MERGE (t:FollowUpType {{id: {q(t['id'])}}})\n"
      f"SET t.ownerModule = {q(t['ownerModule'])}, t.hierarchyTier = {q(t['tier'])}, t.resolveMode = {q(t['resolveMode'])},"
      f" t.deepLinkTemplate = {q(t['deepLinkTemplate']) if t.get('deepLinkTemplate') else 'null'},"
      f" t.staleAfterHours = {int(t['staleAfterHours'])}, t.missedPath = {q(t['missedPath'])},"
      f" t.notifyPush = {str(t['notify']['push']).lower()}, t.notifyInTab = {str(t['notify']['inTab']).lower()},"
      f" t.notifyIcs = {str(t['notify']['ics']).lower()}, t.enabled = {str(t['enabled']).lower()},"
      f" t.reserved = {str(bool(t.get('reserved'))).lower()}, t.reviewStatus = {q(REVIEW_STATUS)},"
      f" t.version = {q(VERSION)}, t.contentJson = {js(content)};")

A("\n// --- Clinical sources for the new skills ---")
for id_, title, url in SOURCES:
    A(f"MERGE (s:ClinicalSource {{id: {q(id_)}}})\nSET s.title = {q(title)}, s.url = {q(url)};")

A("\n// --- PracticeSkill: fields on Recover's skills (their own content stays in invalidation-recovery.cypher) ---")
for sid, f in SKILL_FIELDS.items():
    A(f"MERGE (k:PracticeSkill {{id: {q(sid)}}})\nSET k.defaultFor = {q(f['defaultFor'])}, k.displayLabel = {q(f['displayLabel'])};")

A("\n// --- New PracticeSkills (only their own links are refreshed) ---")
new_ids = [s[0] for s in NEW_SKILLS]
A(f"MATCH (k:PracticeSkill)-[r:PRACTICES|SUPPORTED_BY]->() WHERE k.id IN {q(new_ids)} DELETE r;")
for sid, name, grade, fam, concept, why, sources, default_for in NEW_SKILLS:
    basis = "Limited trials" if grade == "Preliminary" else None
    A(f"MERGE (k:PracticeSkill {{id: {q(sid)}}})\nSET k.name = {q(name)}, k.displayLabel = {q(name)}, k.evidenceGrade = {q(grade)},"
      f" k.evidenceBasis = {q(basis) if basis else 'null'}, k.family = {q(fam)}, k.why = {q(why)},"
      f" k.defaultFor = {q(default_for)}, k.reviewStatus = {q(REVIEW_STATUS)};")
    A(f"MATCH (k:PracticeSkill {{id: {q(sid)}}}), (c:TherapyConcept {{id: {q(concept)}}})\nMERGE (k)-[:PRACTICES]->(c);")
    if sources:
        A(f"UNWIND {q(sources)} AS srcId\nMATCH (k:PracticeSkill {{id: {q(sid)}}}), (s:ClinicalSource {{id: srcId}})\nMERGE (k)-[:SUPPORTED_BY]->(s);")

A("\n// --- The Practice home (MF-02): the MF sequence, the library's names, the other tools that practise each skill ---")
for sid, order, label, also in MF_SEQUENCE:
    own = next(x[-1] for x in NEW_SKILLS if x[0] == sid)
    tools = own + also
    lead = MF_LEADS.get(sid)
    if lead:
        assert lead in tools, f"{sid}: lead tool {lead} doesn't practise it"
        tools = [lead] + [t for t in tools if t != lead]
    A(f"MATCH (k:PracticeSkill {{id: {q(sid)}}})\nSET k.mfOrder = {order}, k.practiceLabel = {q(label)}, k.defaultFor = {q(tools)};")
print("\n".join(L))
