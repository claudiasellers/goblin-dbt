// scripts/opposite-action/content.py is the one editable source of schema/opposite-action-data.cypher (protocol
// metadata, ActionUrge nodes, per-word OA mapping, behaviour urges). The file is what build.py generates.
import { test } from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";

test("schema/opposite-action-data.cypher is what scripts/opposite-action/build.py generates", () => {
  assert.doesNotThrow(() => execFileSync("python3", ["scripts/opposite-action/build.py", "--check"], { encoding: "utf8" }));
});

test("the generated file says where to edit it", () => {
  const text = readFileSync("schema/opposite-action-data.cypher", "utf8");
  assert.match(text, /GENERATED by scripts\/opposite-action\/build\.py from scripts\/opposite-action\/content\.py/);
});
